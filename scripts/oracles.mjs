#!/usr/bin/env node
// The oracles of the ports: the originals each port was measured against (`port/oracle`, `proof/oracle`).
//
// They are not vendored. ports/oracles.lock.json names, for every oracle, the repository and the full commit it is fetched at
// and the SHA-256 digest of the tree that fetch must produce; `npm run oracles:fetch` downloads them into their place (git
// ignored), checks every digest, and fails on any difference. A copy stays in the repository only where the upstream is gone or
// unreachable, and the lock says why. Licence texts and any file Pigpen added or changed stay tracked (`kept`).
//
//   node scripts/oracles.mjs fetch [--cache DIR] [--only ID]   download and verify the fetched oracles
//   node scripts/oracles.mjs verify                            check the digests of the oracles that are in place (offline)
//   node scripts/oracles.mjs check                             check the lock against the tree, ports and provenance (offline)
//   node scripts/oracles.mjs generate                          rewrite the git-ignore block for the fetched oracles
//   node scripts/oracles.mjs prune                             delete the fetched files (what is left is `kept`)
//   node scripts/oracles.mjs analyze [--cache DIR] [--write]   derive the lock from the vendored copies (needs the network)
//
// The cache (default ~/.cache/pigpen-oracles, or $PIGPEN_ORACLE_CACHE) is a set of bare git repositories; CI caches it keyed on the
// lock file.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const LOCK_FILE = 'ports/oracles.lock.json';
export const IGNORE_BEGIN = '# oracles:begin (generated by npm run generate; do not edit)';
export const IGNORE_END = '# oracles:end';
const SKIP = new Set(['node_modules', '.git']);
const HEX40 = /^[0-9a-f]{40}$/;
const slash = (path) => path.split(sep).join('/');

export const readLock = (directory = root) => JSON.parse(readFileSync(join(directory, LOCK_FILE), 'utf8'));
export const lockText = (lock) => JSON.stringify(lock, null, 2) + '\n';

/** Where an oracle of the lock sits in the repository. */
export const placeOf = (directory, entry) => join(directory, 'components', entry.component, entry.path);

/**
 * The files below `path` (or `path` itself, a file), as sorted forward-slash paths relative to it. Symlinks are refused. A directory named
 * node_modules is skipped (an install of the original's dependencies lands there and must not change a digest) unless `modules` is set:
 * an upstream may track such a directory as a test fixture, and then it is part of the original.
 */
export function listFiles(path, { modules = false } = {}) {
  const stat = lstatSync(path);
  if (stat.isSymbolicLink()) throw new Error(`${path}: symlinks are not oracle source`);
  if (stat.isFile()) return [''];
  const found = [];
  const walk = (dir, prefix) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (SKIP.has(entry.name) && !(modules && entry.name === 'node_modules')) continue;
      const full = join(dir, entry.name);
      if (entry.isSymbolicLink()) throw new Error(`${full}: symlinks are not oracle source`);
      if (entry.isDirectory()) walk(full, `${prefix}${entry.name}/`);
      else found.push(`${prefix}${entry.name}`);
    }
  };
  walk(path, '');
  return found.sort();
}

/** {files, bytes, sha256}: the digest covers every file's relative path and content hash, never the mode or the time. */
export function treeDigest(path) {
  const hash = createHash('sha256');
  let bytes = 0;
  const names = listFiles(path);
  for (const name of names) {
    const content = readFileSync(name ? join(path, name) : path);
    bytes += content.length;
    hash.update(`${name}\0${createHash('sha256').update(content).digest('hex')}\n`);
  }
  return { files: names.length, bytes, sha256: hash.digest('hex') };
}

/** The repository URL without a /tree/... suffix, a .git suffix or a trailing slash, lower-cased: for comparing a lock URL with a provenance URL. */
export const normalizeUrl = (url) => url.replace(/\/tree\/.*$/, '').replace(/\.git$/, '').replace(/\/+$/, '').toLowerCase();

function run(args, { git, input, buffer = false, allowFail = false } = {}) {
  const result = spawnSync('git', git ? ['--git-dir', git, ...args] : args, { input, encoding: buffer ? undefined : 'utf8', maxBuffer: 1 << 30, env: { ...process.env, GIT_TERMINAL_PROMPT: '0' } });
  if (result.status !== 0 && !allowFail) throw new Error(`git ${args.join(' ')}: ${String(result.stderr).trim()}`);
  return result;
}

export const defaultCache = () => process.env.PIGPEN_ORACLE_CACHE || join(homedir(), '.cache', 'pigpen-oracles');

/** A bare repository in `cache` that holds `commit` of `repository`; fetches it (that one commit, no history) when it is missing. */
export function ensureCommit(repository, commit, cache = defaultCache()) {
  if (!HEX40.test(commit)) throw new Error(`${repository}: ${commit} is not a full commit hash`);
  const gitDir = join(cache, repository.replace(/^[a-z]+:\/\//, '').replace(/[^A-Za-z0-9._-]+/g, '__') + '.git');
  mkdirSync(cache, { recursive: true });
  if (!existsSync(gitDir)) run(['init', '--bare', '-q', gitDir]);
  const has = () => run(['cat-file', '-e', `${commit}^{commit}`], { git: gitDir, allowFail: true }).status === 0;
  if (has()) return gitDir;
  let last;
  for (let attempt = 0; attempt < 3; attempt++) {
    last = run(['fetch', '--depth', '1', '--no-tags', '-q', repository, commit], { git: gitDir, allowFail: true });
    if (last.status === 0 && has()) return gitDir;
  }
  throw new Error(`${repository}: cannot fetch ${commit}: ${String(last.stderr).trim() || 'the commit is not there'}`);
}

/** [{path, sha, mode}] of the blobs of `commit` below `from` ('' is the whole tree; a file is itself), read from the bare repository. */
export function listTree(gitDir, commit, from = '') {
  const out = run(['ls-tree', '-r', '-z', commit, ...(from ? ['--', from] : [])], { git: gitDir }).stdout;
  return out.split('\0').filter(Boolean).map((line) => {
    const [meta, path] = [line.slice(0, line.indexOf('\t')), line.slice(line.indexOf('\t') + 1)];
    const [mode, type, sha] = meta.split(' ');
    return { path, sha, mode, type };
  }).filter((entry) => entry.type === 'blob' && entry.mode !== '120000');
}

/** Blob contents by sha: Map(sha -> Buffer), read in one `git cat-file --batch`. */
export function readBlobs(gitDir, shas) {
  const unique = [...new Set(shas)];
  const out = run(['cat-file', '--batch'], { git: gitDir, input: unique.join('\n') + '\n', buffer: true }).stdout;
  const blobs = new Map();
  let at = 0;
  for (const sha of unique) {
    const eol = out.indexOf(0x0a, at);
    const [got, type, size] = out.toString('latin1', at, eol).split(' ');
    if (got !== sha || type !== 'blob') throw new Error(`git cat-file: expected blob ${sha}, got ${out.toString('latin1', at, eol)}`);
    blobs.set(sha, out.subarray(eol + 1, eol + 1 + Number(size)));
    at = eol + 1 + Number(size) + 1;
  }
  return blobs;
}

/** The git blob id of `content`, to find it in a tree without reading the tree's blobs. */
export const blobSha = (content) => createHash('sha1').update(`blob ${content.length}\0`).update(content).digest('hex');

/** Whether `rel` is selected by `include`: an entry ending in / is a directory, any other is one file. No `include` selects everything. */
export const included = (include, rel) => !include || include.some((entry) => (entry.endsWith('/') ? rel.startsWith(entry) : rel === entry));

/** What a fetch of `entry` yields, before anything is written: Map(path relative to the oracle -> {sha}). */
export function planFetch(entry, gitDir) {
  const files = new Map();
  for (const { from, to } of entry.map) {
    const tree = listTree(gitDir, entry.commit, from);
    if (!tree.length) throw new Error(`${entry.id}: ${from} is not in ${entry.repository} at ${entry.commit}`);
    for (const blob of tree) {
      const inside = from && blob.path === from ? '' : blob.path.slice(from ? from.length + 1 : 0);
      const rel = slash(join(to, inside));
      if (included(entry.include, rel)) files.set(rel, { sha: blob.sha });
    }
  }
  return files;
}

/** Fetch `entry` into its place and verify the digest. Files named in `kept` are the repository's own and are never overwritten. */
export function materialize(entry, { directory = root, cache = defaultCache() } = {}) {
  const place = placeOf(directory, entry);
  const kept = new Set(entry.kept ?? []);
  const current = existsSync(place) ? safeDigest(place) : null;
  if (current && current.sha256 === entry.sha256) return { ...current, fetched: false };
  const gitDir = ensureCommit(entry.repository, entry.commit, cache);
  const plan = planFetch(entry, gitDir);
  const blobs = readBlobs(gitDir, [...plan.values()].map(({ sha }) => sha));
  const isFile = entry.map.length === 1 && plan.size === 1 && plan.has('') ;
  for (const [rel, { sha }] of plan) {
    if (kept.has(rel)) continue;
    const target = rel ? join(place, rel) : place;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, blobs.get(sha));
  }
  const after = treeDigest(place);
  if (after.sha256 !== entry.sha256) throw new Error(`${entry.id}: the fetched tree does not match the lock (${after.files} files, sha256 ${after.sha256}, the lock says ${entry.files} files, ${entry.sha256}). ${describeDifference(entry, place, plan, blobs)}`);
  return { ...after, fetched: true, isFile };
}

const safeDigest = (place) => { try { return treeDigest(place); } catch { return null; } };

function describeDifference(entry, place, plan, blobs) {
  const have = new Set(listFiles(place));
  const extra = [...have].filter((rel) => !plan.has(rel) && !(entry.kept ?? []).includes(rel));
  const changed = [...plan].filter(([rel, { sha }]) => have.has(rel) && !(entry.kept ?? []).includes(rel) && blobSha(readFileSync(rel ? join(place, rel) : place)) !== sha).map(([rel]) => rel);
  return `Files not in the fetch: ${extra.slice(0, 5).join(', ') || 'none'}. Changed after the fetch: ${changed.slice(0, 5).join(', ') || 'none'}.`;
}

/** A line for .gitignore for every fetched oracle (relative to the repository root). */
export const ignoreLines = (lock) => lock.oracles.filter((entry) => entry.source === 'fetched').map((entry) => `/components/${entry.component}/${entry.path}${entry.isFile ? '' : '/'}`).sort();

/** `text` (the .gitignore) with the oracle block regenerated from the lock. */
export function withIgnoreBlock(text, lock) {
  const block = [IGNORE_BEGIN, ...ignoreLines(lock).map((line) => line), IGNORE_END].join('\n');
  const pattern = new RegExp(`${IGNORE_BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${IGNORE_END}`);
  return pattern.test(text) ? text.replace(pattern, block) : text.replace(/\n*$/, '\n') + block + '\n';
}

/** The oracle directories of the tree: every directory named oracle or oracle-* directly below a component's port/ or proof/. */
export function oracleDirectories(directory = root) {
  const found = [];
  const components = join(directory, 'components');
  if (!existsSync(components)) return found;
  for (const component of readdirSync(components, { withFileTypes: true })) {
    if (!component.isDirectory()) continue;
    for (const holder of ['port', 'proof']) {
      const base = join(components, component.name, holder);
      if (!existsSync(base)) continue;
      for (const entry of readdirSync(base, { withFileTypes: true })) if (entry.isDirectory() && /^oracle(-.+)?$/.test(entry.name)) found.push(`${component.name}/${holder}/${entry.name}`);
    }
  }
  return found.sort();
}

/** Every way the lock disagrees with the repository: problems as sentences, none when it holds. Offline. */
export function lockProblems(directory = root) {
  const problems = [];
  let lock;
  try { lock = readLock(directory); } catch (error) { return [`${LOCK_FILE}: ${error.message}`]; }
  const ids = new Set();
  const tracked = trackedFiles(directory);
  for (const entry of lock.oracles ?? []) {
    const where = `${LOCK_FILE}: ${entry.id}`;
    if (!entry.id || ids.has(entry.id)) problems.push(`${where}: the id is missing or repeated`);
    ids.add(entry.id);
    if (!['fetched', 'vendored'].includes(entry.source)) problems.push(`${where}: source must be fetched or vendored`);
    if (!HEX40.test(entry.commit ?? '')) problems.push(`${where}: commit must be a full 40-character hash`);
    if (!/^[0-9a-f]{64}$/.test(entry.sha256 ?? '')) problems.push(`${where}: sha256 must be the 64-character tree digest`);
    if (entry.source === 'vendored' && !String(entry.reason ?? '').trim()) problems.push(`${where}: a vendored oracle must say why it is not fetched (reason)`);
    if (entry.source === 'fetched' && !Array.isArray(entry.map)) problems.push(`${where}: a fetched oracle needs map: [{from, to}]`);
    // The commit and URL are the port's pin: the lock must say what provenance.json and ports.json say.
    const pinned = pins(directory, entry);
    if (!pinned.some((pin) => pin.commit === entry.commit && normalizeUrl(pin.url) === normalizeUrl(entry.repository))) problems.push(`${where}: ${entry.repository} at ${entry.commit} is not a pin in components/${entry.component}/provenance.json or ports/ports.json`);
    const place = placeOf(directory, entry);
    if (entry.source === 'vendored') {
      if (!existsSync(place)) problems.push(`${where}: the vendored copy components/${entry.component}/${entry.path} is missing`);
      else if (safeDigest(place)?.sha256 !== entry.sha256) problems.push(`${where}: the vendored copy no longer matches its digest; the lock records what was vendored`);
    } else if (tracked) {
      const prefix = `components/${entry.component}/${entry.path}`;
      const kept = new Set((entry.kept ?? []).map((rel) => (rel ? `${prefix}/${rel}` : prefix)));
      for (const file of tracked) if ((file === prefix || file.startsWith(prefix + '/')) && !kept.has(file)) problems.push(`${where}: ${file} is tracked but is neither fetched nor listed in kept; delete it or list it`);
    }
  }
  const known = new Set((lock.oracles ?? []).map((entry) => `${entry.component}/${entry.path}`));
  const covering = (dir) => [...known].some((path) => path === dir || path.startsWith(dir + '/') || dir.startsWith(path + '/'));
  for (const dir of oracleDirectories(directory)) {
    if (!covering(dir)) problems.push(`components/${dir} is an oracle that ${LOCK_FILE} does not list. An original is fetched, not vendored: add it to the lock (node scripts/oracles.mjs analyze) with the commit pinned in its provenance.json; a copy stays tracked only with source "vendored" and a reason.`);
  }
  const ignorePath = join(directory, '.gitignore');
  if (existsSync(ignorePath) && withIgnoreBlock(readFileSync(ignorePath, 'utf8'), lock) !== readFileSync(ignorePath, 'utf8')) problems.push('.gitignore: the oracle block is stale; run npm run generate');
  return problems;
}

/** The pins that may justify an oracle's commit: the component's provenance upstreams and the ports.json upstream of its target. */
function pins(directory, entry) {
  const found = [];
  const provenance = join(directory, 'components', entry.component, 'provenance.json');
  if (existsSync(provenance)) for (const upstream of JSON.parse(readFileSync(provenance, 'utf8')).upstreams ?? []) found.push({ url: upstream.url, commit: upstream.revision });
  const portsFile = join(directory, 'ports/ports.json');
  if (existsSync(portsFile)) for (const port of JSON.parse(readFileSync(portsFile, 'utf8')).ports ?? []) if (port.upstream && port.targetPackage === `components/${entry.component}`) found.push({ url: port.upstream.url, commit: port.upstream.commit });
  return found;
}

function trackedFiles(directory) {
  if (!existsSync(join(directory, '.git'))) return null;
  const result = spawnSync('git', ['-C', directory, 'ls-files', '-z', '--', 'components'], { encoding: 'utf8', maxBuffer: 1 << 28 });
  return result.status === 0 ? result.stdout.split('\0').filter(Boolean) : null;
}

/** Fetch every fetched oracle (or `only`); returns [{id, files, bytes, fetched}]. */
export function fetchAll({ directory = root, cache = defaultCache(), only, log = () => {} } = {}) {
  const lock = readLock(directory);
  const done = [];
  for (const entry of lock.oracles) {
    if (entry.source !== 'fetched' || (only && entry.id !== only)) continue;
    const result = materialize(entry, { directory, cache });
    log(`${entry.id}: ${result.fetched ? 'fetched' : 'already in place'}, ${result.files} files, sha256 ${result.sha256.slice(0, 12)}`);
    done.push({ id: entry.id, ...result });
  }
  return done;
}

/** Whether `absolute` is, or is inside, an oracle the lock fetches (it may not be in place yet). */
export function isFetchedPath(directory, absolute) {
  if (!existsSync(join(directory, LOCK_FILE))) return false;
  return readLock(directory).oracles.some((entry) => {
    if (entry.source !== 'fetched') return false;
    const place = placeOf(directory, entry);
    return absolute === place || absolute.startsWith(place + sep);
  });
}

/** The fetched oracles that are not in place (or not what the lock says), as sentences: what a test that reads one checks first. */
export function missingOracles(directory = root, component) {
  const lock = readLock(directory);
  const missing = [];
  for (const entry of lock.oracles) {
    if (entry.source !== 'fetched' || (component && entry.component !== component)) continue;
    const place = placeOf(directory, entry);
    const digest = existsSync(place) ? safeDigest(place) : null;
    if (!digest) missing.push(`components/${entry.component}/${entry.path} is not in place`);
    else if (digest.sha256 !== entry.sha256) missing.push(`components/${entry.component}/${entry.path} does not match ${LOCK_FILE}`);
  }
  return missing;
}

/** Throw with the one command that fixes it when a fetched oracle is missing. */
export function requireOracles(directory = root) {
  const missing = missingOracles(directory);
  if (missing.length) throw new Error(`${missing.join('; ')}. The originals are fetched, not vendored: run npm run oracles:fetch.`);
}

/** Delete the fetched files of every fetched oracle (everything but `kept`), then the empty directories: how the vendored copies were removed. */
export function prune(directory = root) {
  let removed = 0;
  for (const entry of readLock(directory).oracles) {
    if (entry.source !== 'fetched') continue;
    const place = placeOf(directory, entry);
    if (!existsSync(place)) continue;
    const kept = new Set(entry.kept ?? []);
    for (const rel of listFiles(place, { modules: true })) if (!kept.has(rel)) { rmSync(rel ? join(place, rel) : place, { force: true }); removed++; }
    if (existsSync(place) && lstatSync(place).isDirectory()) {
      const empty = (dir) => { for (const e of readdirSync(dir, { withFileTypes: true })) if (e.isDirectory()) empty(join(dir, e.name)); if (!readdirSync(dir).length && dir !== place) rmSync(dir, { recursive: true }); };
      empty(place);
    }
  }
  return removed;
}

// ---- analyze: derive the lock from the copies that are vendored today -------------------------------------------------------

/** The provenance upstreams that point at an oracle path: [{component, path, url, commit, name}]. */
function oracleUpstreams(directory) {
  const found = [];
  for (const dir of readdirSync(join(directory, 'components')).sort()) {
    const file = join(directory, 'components', dir, 'provenance.json');
    if (!existsSync(file)) continue;
    for (const upstream of JSON.parse(readFileSync(file, 'utf8')).upstreams ?? []) {
      if (upstream.path && /(^|\/)oracle[^/]*(\/|$)/.test(upstream.path)) found.push({ component: dir, path: upstream.path, url: upstream.url, commit: upstream.revision, name: upstream.name });
    }
  }
  return found;
}

/** Where in the upstream tree a vendored directory (or file) came from: the prefix whose files match the most of its files. */
export function findSource(gitDir, commit, vendored) {
  const tree = listTree(gitDir, commit);
  const byBlob = new Map();
  for (const { path, sha } of tree) { if (!byBlob.has(sha)) byBlob.set(sha, []); byBlob.get(sha).push(path); }
  const votes = new Map();
  for (const [rel, sha] of vendored) {
    for (const path of byBlob.get(sha) ?? []) {
      const prefix = rel === '' ? path : path.endsWith('/' + rel) ? path.slice(0, -rel.length - 1) : path === rel ? '' : null;
      if (prefix !== null) votes.set(prefix, (votes.get(prefix) ?? 0) + 1);
    }
  }
  const ranked = [...votes].sort((a, b) => b[1] - a[1] || a[0].length - b[0].length);
  return { tree, prefix: ranked.length ? ranked[0][0] : null, votes: ranked.length ? ranked[0][1] : 0 };
}

/** The include list that selects exactly the upstream files (under the prefix) that the vendored copy holds unchanged. */
export function includeList(upstreamFiles, identical) {
  const names = upstreamFiles.map((path) => path);
  const out = [];
  const build = (prefix, files) => {
    const children = new Map();
    for (const path of files) {
      const rest = path.slice(prefix.length);
      const slashAt = rest.indexOf('/');
      const name = slashAt < 0 ? rest : rest.slice(0, slashAt + 1);
      if (!children.has(name)) children.set(name, []);
      children.get(name).push(path);
    }
    for (const [name, under] of children) {
      const hits = under.filter((path) => identical.has(path)).length;
      if (!hits) continue;
      if (hits === under.length) out.push(prefix + name);
      else if (name.endsWith('/')) build(prefix + name, under);
      else out.push(prefix + name);
    }
  };
  build('', names);
  return out.sort();
}

export function analyze({ directory = root, cache = defaultCache(), log = console.log } = {}) {
  const entries = [];
  for (const upstream of oracleUpstreams(directory)) {
    const id = `${upstream.component}${upstream.path.replace(/^port\/oracle|^proof\/oracle/, '').replace(/\//g, '-')}`.replace(/-$/, '');
    const place = join(directory, 'components', upstream.component, upstream.path);
    if (!existsSync(place)) { log(`${id}: ${upstream.path} is not vendored here`); continue; }
    const vendored = new Map(listFiles(place, { modules: true }).map((rel) => [rel, blobSha(readFileSync(rel ? join(place, rel) : place))]));
    const digest = treeDigest(place);
    const base = { id, component: upstream.component, path: upstream.path, repository: upstream.url.replace(/\/tree\/.*$/, '').replace(/\/+$/, ''), commit: upstream.commit };
    let gitDir;
    try { gitDir = ensureCommit(base.repository, base.commit, cache); } catch (error) {
      entries.push({ ...base, source: 'vendored', reason: `the upstream cannot be fetched at the pinned commit: ${error.message.split('\n')[0]}`, files: digest.files, bytes: digest.bytes, sha256: digest.sha256 });
      log(`${id}: UNREACHABLE ${error.message.split('\n')[0]}`);
      continue;
    }
    const { tree, prefix, votes } = findSource(gitDir, base.commit, vendored);
    if (prefix === null) {
      entries.push({ ...base, source: 'vendored', reason: 'no file of the copy is in the upstream at the pinned commit', files: digest.files, bytes: digest.bytes, sha256: digest.sha256 });
      log(`${id}: NO MATCH`);
      continue;
    }
    const isFile = vendored.has('') ;
    const underPrefix = tree.filter((t) => (prefix === '' ? true : t.path.startsWith(prefix + '/') || t.path === prefix));
    const rel = (path) => (isFile ? '' : prefix ? path.slice(prefix.length + 1) : path);
    // The upstream's licence text at the top of the oracle stays tracked: it travels with a Git-tag install of the Package.
    const licence = (r) => !isFile && !r.includes('/') && /^(LICEN[CS]E|NOTICE|COPYING)(\.|$)/i.test(r);
    const same = new Set(underPrefix.filter((t) => vendored.get(rel(t.path)) === t.sha && !licence(rel(t.path))).map((t) => rel(t.path)));
    const upstreamRel = underPrefix.map((t) => rel(t.path));
    const include = isFile ? null : includeList(upstreamRel, same);
    const kept = [...vendored.keys()].filter((r) => !same.has(r)).sort();
    const entry = { ...base, source: 'fetched', map: [{ from: prefix, to: '' }], ...(include ? { include } : {}), ...(isFile ? { isFile: true } : {}), kept, files: digest.files, bytes: digest.bytes, sha256: digest.sha256 };
    entries.push(entry);
    const keptBytes = kept.reduce((n, r) => n + readFileSync(r ? join(place, r) : place).length, 0);
    log(`${id}: ${vendored.size} files, from ${prefix || '/'} (${votes} matched), kept ${kept.length} (${keptBytes} bytes), include ${include ? include.length : 'file'}`);
  }
  return { schemaVersion: 1, oracles: entries.sort((a, b) => a.id.localeCompare(b.id, 'en')) };
}

// ---- command line -------------------------------------------------------------------------------------------------------------

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [command, ...args] = process.argv.slice(2);
  const flag = (name) => { const at = args.indexOf(name); return at < 0 ? undefined : args[at + 1]; };
  const cache = flag('--cache') ?? defaultCache();
  try {
    if (command === 'fetch') {
      const done = fetchAll({ cache, only: flag('--only'), log: console.log });
      console.log(`${done.length} oracles in place, ${done.reduce((n, d) => n + d.files, 0)} files`);
    } else if (command === 'verify') {
      const missing = missingOracles();
      if (missing.length) throw new Error(`${missing.join('\n')}\nrun npm run oracles:fetch`);
      console.log('Every fetched oracle is in place and matches the lock');
    } else if (command === 'check') {
      const problems = lockProblems();
      if (problems.length) throw new Error(problems.join('\n'));
      console.log(`Oracle lock passed: ${readLock().oracles.length} oracles`);
    } else if (command === 'generate') {
      const lock = readLock();
      const path = join(root, '.gitignore');
      writeFileSync(path, withIgnoreBlock(readFileSync(path, 'utf8'), lock));
      console.log('Wrote the oracle block of .gitignore');
    } else if (command === 'prune') {
      console.log(`Removed ${prune()} fetched files`);
    } else if (command === 'analyze') {
      const lock = analyze({ cache });
      if (args.includes('--write')) writeFileSync(join(root, LOCK_FILE), lockText(lock));
      console.log(`${lock.oracles.length} oracles (${lock.oracles.filter((e) => e.source === 'fetched').length} fetched, ${lock.oracles.filter((e) => e.source === 'vendored').length} vendored)`);
    } else throw new Error('usage: node scripts/oracles.mjs fetch|verify|check|generate|prune|analyze');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
