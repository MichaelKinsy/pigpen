// Drift check for the dev-skills Package. Its Skills are deliberate adaptations of two public repositories, so
// "unchanged from upstream" is not the test. The test is that every shipped file is mapped to the upstream file it
// was adapted from, at the commit the adaptation is based on, with its adaptations listed:
//
//   components/dev-skills/port/upstream-map.json   the map (one row per shipped file, plus the licenses)
//   components/dev-skills/CREDITS.md               carries a table generated from the map (--write)
//
// Offline (default, and part of `npm run quality`):
//   - every shipped Markdown file under skills/ has a row, and every row names a file that exists;
//   - each row's upstream pin equals provenance.json's revision for that repository;
//   - each vendored copy under upstream/ has the git blob id the row records, which is the blob id of the upstream
//     file at the pinned commit (so the copy is what upstream has, byte for byte);
//   - the shipped file's sha256 equals the row's: editing a Skill without revisiting its adaptations list fails;
//   - the shipped file says, at its top, which upstream Skill and commit it is adapted from;
//   - the generated table in CREDITS.md is current.
//
// Online (network, not run in CI), same git hardening as `ports.mjs verify-pins`:
//   --online   fetch each pinned commit and require the recorded blob id for every mapped upstream path;
//   --latest   fetch each upstream's default branch and list the mapped paths that changed since the pin (drift the
//              next re-base has to read; informational unless --fail-on-drift).
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultRoot = fileURLToPath(new URL('../', import.meta.url));
const COMPONENT = 'components/dev-skills';
const BEGIN = '<!-- dev-skills-map:begin (generated by scripts/dev-skills-drift.mjs --write; do not edit) -->';
const END = '<!-- dev-skills-map:end -->';

export const gitBlobId = (buf) => createHash('sha1').update(`blob ${buf.length}\0`).update(buf).digest('hex');
export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const short = (sha) => sha.slice(0, 7);

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else yield path;
  }
}

/** The CREDITS.md block for a map: one table row per shipped file. */
export function renderTable(map) {
  const lines = [
    '| Skill file here | Upstream file | Pinned commit | Adaptations |',
    '|---|---|---|---|',
  ];
  for (const row of map.skills) {
    const source = map.sources[row.source];
    const changes = row.adaptations.map((a) => a.replaceAll('|', '\\|')).join(' ');
    lines.push(`| \`${row.shipped}\` | \`${row.source}\` \`${row.path}\` (copy: \`${row.vendored}\`) | \`${short(source.commit)}\` | ${changes} |`);
  }
  return `${BEGIN}\n${lines.join('\n')}\n${END}`;
}

/** Offline problems, as a list of strings (empty: the Package matches its map). */
export function checkDevSkills(root = defaultRoot) {
  const errors = [];
  const dir = join(root, COMPONENT);
  const mapPath = join(dir, 'port/upstream-map.json');
  if (!existsSync(mapPath)) return [`${COMPONENT}/port/upstream-map.json is missing`];
  const map = readJson(mapPath);
  const provenance = readJson(join(dir, 'provenance.json'));

  for (const [name, source] of Object.entries(map.sources)) {
    if (!/^[0-9a-f]{40}$/.test(source.commit)) errors.push(`source ${name}: commit must be a full 40-hex id`);
    const pinned = provenance.upstreams.find((u) => u.name === name);
    if (!pinned) errors.push(`source ${name}: provenance.json has no upstream of that name`);
    else {
      if (pinned.revision !== source.commit) errors.push(`source ${name}: map pins ${short(source.commit)}, provenance.json pins ${short(pinned.revision)}`);
      if (pinned.url !== source.url) errors.push(`source ${name}: map url ${source.url} differs from provenance.json ${pinned.url}`);
    }
  }
  for (const u of provenance.upstreams) if (!map.sources[u.name]) errors.push(`provenance.json upstream ${u.name} has no source in the map`);

  const mapped = new Set();
  for (const row of map.skills) {
    const where = `skill ${row.shipped}`;
    mapped.add(row.shipped);
    const source = map.sources[row.source];
    if (!source) { errors.push(`${where}: unknown source ${row.source}`); continue; }
    if (!Array.isArray(row.adaptations) || row.adaptations.length === 0 || row.adaptations.some((a) => typeof a !== 'string' || !a.trim())) {
      errors.push(`${where}: list its adaptations (at least one, each a sentence)`);
    }
    const shipped = join(dir, row.shipped);
    if (!existsSync(shipped)) errors.push(`${where}: the shipped file does not exist`);
    else {
      const bytes = readFileSync(shipped);
      if (sha256(bytes) !== row.adaptedSha256) errors.push(`${where}: edited since its row was written (sha256 ${sha256(bytes).slice(0, 12)}, row ${String(row.adaptedSha256).slice(0, 12)}): re-read its adaptations list against the upstream copy, then update adaptedSha256`);
      const head = bytes.toString('utf8').split('\n', 12).join('\n');
      if (!head.includes(row.source) || !head.includes(short(source.commit))) errors.push(`${where}: its opening note must name ${row.source} and the pinned commit ${short(source.commit)}`);
    }
    const vendored = join(dir, row.vendored);
    if (!existsSync(vendored)) errors.push(`${where}: the vendored upstream copy ${row.vendored} does not exist`);
    else if (gitBlobId(readFileSync(vendored)) !== row.upstreamBlob) errors.push(`${where}: ${row.vendored} is not the upstream blob ${short(row.upstreamBlob)} (it was edited, or the row is wrong)`);
    if (!/^[0-9a-f]{40}$/.test(row.upstreamBlob)) errors.push(`${where}: upstreamBlob must be a full 40-hex blob id`);
  }
  for (const [name, license] of Object.entries(map.licenses)) {
    const vendored = join(dir, license.vendored);
    if (!map.sources[name]) errors.push(`license ${name}: no such source`);
    else if (!existsSync(vendored)) errors.push(`license ${name}: ${license.vendored} does not exist`);
    else if (gitBlobId(readFileSync(vendored)) !== license.upstreamBlob) errors.push(`license ${name}: ${license.vendored} is not the upstream blob ${short(license.upstreamBlob)}`);
  }

  const skillsDir = join(dir, 'skills');
  for (const file of walk(skillsDir)) {
    const rel = relative(dir, file).split('\\').join('/');
    if (!mapped.has(rel)) errors.push(`${rel}: shipped but not in upstream-map.json (map it to its upstream file, or say in the map that it is original)`);
  }

  const credits = readFileSync(join(dir, 'CREDITS.md'), 'utf8');
  const start = credits.indexOf(BEGIN);
  const end = credits.indexOf(END);
  if (start < 0 || end < start) errors.push('CREDITS.md has no generated map block (run node scripts/dev-skills-drift.mjs --write)');
  else if (credits.slice(start, end + END.length) !== renderTable(map)) errors.push('CREDITS.md map table is out of date (run node scripts/dev-skills-drift.mjs --write)');
  return errors;
}

/** Rewrite the generated block of CREDITS.md from the map. */
export function writeCredits(root = defaultRoot) {
  const dir = join(root, COMPONENT);
  const map = readJson(join(dir, 'port/upstream-map.json'));
  const path = join(dir, 'CREDITS.md');
  const credits = readFileSync(path, 'utf8');
  const start = credits.indexOf(BEGIN);
  const end = credits.indexOf(END);
  if (start < 0 || end < start) throw new Error('CREDITS.md has no generated map block: add the begin and end markers where the table belongs');
  writeFileSync(path, credits.slice(0, start) + renderTable(map) + credits.slice(end + END.length));
}

// The upstream URLs come from a reviewed file, but never offer one a stored credential, an askpass program or a login.
function gitEnv() {
  const env = { ...process.env, GIT_TERMINAL_PROMPT: '0', GCM_INTERACTIVE: 'never' };
  delete env.GIT_ASKPASS;
  delete env.SSH_ASKPASS;
  return env;
}

function git(dir, args, options = {}) {
  return spawnSync('git', ['-c', 'credential.helper=', '-c', 'core.askPass=', '-C', dir, ...args], { env: gitEnv(), encoding: 'utf8', timeout: 180000, ...options });
}

/** Blob id of `path` at `rev` in the repository at `dir`, or undefined. */
function blobAt(dir, rev, path) {
  const r = git(dir, ['rev-parse', '--verify', '--quiet', `${rev}:${path}`]);
  return r.status === 0 ? r.stdout.trim() : undefined;
}

/** Network checks. `latest` also lists paths that changed upstream since the pin. Returns { errors, drift }. */
export function checkOnline(root = defaultRoot, { latest = false } = {}) {
  const map = readJson(join(root, COMPONENT, 'port/upstream-map.json'));
  const errors = [];
  const drift = [];
  const scratch = mkdtempSync(join(tmpdir(), 'dev-skills-drift-'));
  try {
    for (const [name, source] of Object.entries(map.sources)) {
      const repo = join(scratch, name.replace(/[^\w.-]/g, '_'));
      git(scratch, ['init', '-q', repo]);
      const fetched = git(repo, ['fetch', '-q', '--depth=1', source.url, source.commit]);
      if (fetched.status !== 0) { errors.push(`${name}: cannot fetch ${short(source.commit)} from ${source.url}: ${(fetched.stderr || 'timeout').trim().split('\n').at(-1)}`); continue; }
      const rows = [...map.skills.filter((s) => s.source === name), ...(map.licenses[name] ? [{ shipped: 'LICENSE', path: map.licenses[name].path, upstreamBlob: map.licenses[name].upstreamBlob }] : [])];
      for (const row of rows) {
        const at = blobAt(repo, source.commit, row.path);
        if (at === undefined) errors.push(`${name}: ${row.path} does not exist at ${short(source.commit)}`);
        else if (at !== row.upstreamBlob) errors.push(`${name}: ${row.path} at ${short(source.commit)} is blob ${short(at)}, the map records ${short(row.upstreamBlob)}`);
      }
      if (latest) {
        const head = git(repo, ['fetch', '-q', '--depth=1', source.url, 'HEAD']);
        if (head.status !== 0) { errors.push(`${name}: cannot fetch the default branch of ${source.url}`); continue; }
        const tip = git(repo, ['rev-parse', 'FETCH_HEAD']).stdout.trim();
        for (const row of rows) {
          const now = blobAt(repo, tip, row.path);
          if (now !== row.upstreamBlob) drift.push(`${name} ${row.path}: ${now === undefined ? 'removed or moved' : 'changed'} upstream since ${short(source.commit)} (default branch ${short(tip)})`);
        }
      }
    }
  } finally { rmSync(scratch, { recursive: true, force: true }); }
  return { errors, drift };
}

function main(argv) {
  const args = [...argv];
  const flag = (name) => { const i = args.indexOf(name); if (i < 0) return false; args.splice(i, 1); return true; };
  const rootIndex = args.indexOf('--root');
  let root = defaultRoot;
  if (rootIndex >= 0) { root = resolve(args[rootIndex + 1]); args.splice(rootIndex, 2); }
  const write = flag('--write');
  const online = flag('--online');
  const latest = flag('--latest');
  const failOnDrift = flag('--fail-on-drift');
  if (args.length) { console.error(`unknown argument ${args[0]}\nusage: node scripts/dev-skills-drift.mjs [--root DIR] [--write] [--online] [--latest [--fail-on-drift]]`); return 2; }
  if (write) { writeCredits(root); console.log('Wrote the map table of components/dev-skills/CREDITS.md'); }
  const errors = checkDevSkills(root);
  let drift = [];
  if (online || latest) {
    const result = checkOnline(root, { latest });
    errors.push(...result.errors);
    drift = result.drift;
  }
  if (errors.length) { console.error(errors.join('\n')); return 1; }
  const count = readJson(join(root, COMPONENT, 'port/upstream-map.json')).skills.length;
  console.log(`dev-skills drift check passed: ${count} shipped files mapped${online || latest ? ', pins verified against upstream' : ''}`);
  for (const line of drift) console.log(`upstream drift: ${line}`);
  if (latest && !drift.length) console.log('upstream drift: none');
  return failOnDrift && drift.length ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
