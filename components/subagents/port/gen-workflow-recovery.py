#!/usr/bin/env python3
"""Generates extensions/pi-subagents/workflow_recovery_patterns.go from the original's RECOVERY_REVIEW_* regular expressions
(scripted-workflow.ts:1285-1320), so the Go port carries them byte for byte. Run from components/subagents."""
import re, json, sys
src = open("port/oracle/src/workflows/scripted-workflow.ts", encoding="utf-8").read().split("\n")
out = ["// Code generated by port/gen-workflow-recovery.py from scripted-workflow.ts:1285-1320; DO NOT EDIT.", "", "package pi_subagents", "",
       'import "github.com/dlclark/regexp2/v2"', "", "// The patterns of isExplicitReadOnlyRecoveryReview, as JavaScript source plus flags.", "var ("]
n = 0
for i in range(1284, 1320):
    m = re.match(r"^const (RECOVERY_REVIEW_[A-Z_]+) = /(.*)/([a-z]*);$", src[i])
    if not m:
        sys.exit("line %d does not match: %r" % (i + 1, src[i][:80]))
    name, pat, flags = m.groups()
    go = "recoveryRe" + "".join(p.capitalize() for p in name[len("RECOVERY_REVIEW_"):].split("_"))
    opts = ["regexp2.ECMAScript"]
    if "i" in flags: opts.append("regexp2.IgnoreCase")
    if "m" in flags: opts.append("regexp2.Multiline")
    out.append("\t%s = regexp2.MustCompile(%s, %s)" % (go, json.dumps(pat, ensure_ascii=False), "|".join(opts)))
    n += 1
out.append(")")
out.append("")
open("extensions/pi-subagents/workflow_recovery_patterns.go", "w", encoding="utf-8").write("\n".join(out))
print(n, "patterns")
