// Generates internal/svc/mimetable.go from the `mime` npm package (broofa/mime, MIT; the table is
// mime-db's, MIT): the extension -> type map that mime.getType() answers from.
//
//   npm pack mime@4.1.1 && tar xzf mime-4.1.1.tgz        # in a scratch directory
//   node proof/tools/gen-mime.mjs <scratch>/package > extensions/ahp/internal/svc/mimetable.go
import { pathToFileURL } from "node:url";
import { join } from "node:path";
import { readFileSync } from "node:fs";

const dir = process.argv[2];
const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const { default: mime } = await import(pathToFileURL(join(dir, "dist/src/index.js")).href);
const types = [...mime._getTestState().types.entries()].sort(([a], [b]) => Buffer.compare(Buffer.from(a), Buffer.from(b)));
const q = (s) => JSON.stringify(s);
process.stdout.write(`// Code generated by proof/tools/gen-mime.mjs from mime@${pkg.version} (MIT, https://github.com/broofa/mime); DO NOT EDIT.
// The table is mime-db's (MIT, https://github.com/jshttp/mime-db), as the \`mime\` package ships it:
// ${types.length} extensions, sorted for binary search so that it costs nothing at start-up.

package svc

// mimeTable maps a lower-case extension (without its dot) to its content type.
var mimeTable = [...]struct{ ext, typ string }{
${types.map(([ext, typ]) => `\t{${q(ext)}, ${q(typ)}},`).join("\n")}
}
`);
