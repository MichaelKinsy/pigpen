// upstream: crates/edit/tests/hashline_patcher.rs: "each_refusal_carries_the_kind_of_check_that_made_it"
func TestEachRefusalCarriesErrorKind(t *testing.T) {
	w := newTestWorkspace(t)
	w.opts.EnforceSeenLines = true
	text := numberedLines(30)
	w.writeFile("a.txt", text)
	shown := w.snapshot("a.txt", text, []uint32{1, 2, 3})
	w.writeFile("b.txt", "old\n")
	stale := w.snapshot("b.txt", "old\n", nil)
	w.writeFile("b.txt", "new\n")

	cases := [][2]string{
		{fmt.Sprintf("[a.txt#%s]\nPUT 20.=20:\n+X\n", shown), "unseen_lines"},
		{fmt.Sprintf("[b.txt#%s]\nPUT 1.=1:\n+X\n", stale), "stale_tag"},
		{fmt.Sprintf("[b.txt#%s]\nPUT 1.=1:\n+X\n", shown), "other_file_tag"},
		{"[a.txt#0000]\nPUT 1.=1:\n+X\n", "unknown_tag"},
		{"[a.txt]\nPUT 1.=1:\n+X\n", "missing_tag"},
		{fmt.Sprintf("[a.txt#%s]\n", shown), "header_only"},
		{"[new.txt]\nPUT 1.=1:\n+X\n", "file_not_found"},
		{"PUT 1.=1:\n+X\n", "parse"},
	}
	for _, tc := range cases {
		_, _, err := w.apply(tc[0])
		if err == nil || err.Kind() != tc[1] {
			t.Fatalf("%q: err=%v kind=%q, want %q", tc[0], err, ErrorKindOf(err), tc[1])
		}
	}
}

