func newTestWorkspace(t *testing.T) *testWorkspace {
	t.Helper()
	return &testWorkspace{
		t:     t,
		dir:   t.TempDir(),
		store: NewStore(),
		opts: StageOptions{
			EnforceSeenLines:   false,
			MaxColumns:         512,
			BlockAutoGenerated: true,
		},
	}
}

func (w *testWorkspace) writeFile(rel, content string) string {
	w.t.Helper()
	p := filepath.Join(w.dir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		w.t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		w.t.Fatal(err)
	}
	return p
}

func (w *testWorkspace) readFile(rel string) (string, bool) {
	b, err := os.ReadFile(filepath.Join(w.dir, rel))
	if err != nil {
		return "", false
	}
	return string(b), true
}

func (w *testWorkspace) snapshot(rel, text string, seen []uint32) string {
	abs := filepath.Join(w.dir, rel)
	if seen == nil {
		return w.store.Record(abs, text, nil, false)
	}
	return w.store.Record(abs, text, seen, true)
}

func (w *testWorkspace) apply(input string) (string, []StagedFile, *EditError) {
	files := &DiskFileSource{
		WorkDir:            w.dir,
		BlockAutoGenerated: w.opts.BlockAutoGenerated,
		PlanWritableRoots:  w.roots,
	}
	staged, err := StageInput(input, files, w.store, w.opts)
	if err != nil {
		return "", nil, err
	}
	var out []string
	for i := range staged {
		f := &staged[i]
		if f.Op != EngineFileOpNoop {
			switch f.Op {
			case EngineFileOpDelete:
				if rErr := os.Remove(f.Absolute); rErr != nil {
					w.t.Fatal(rErr)
				}
				w.store.Invalidate(f.Canonical)
			case EngineFileOpUpdate, EngineFileOpCreate:
				dest := f.Absolute
				if f.MoveTo != nil {
					dest = f.MoveTo.Absolute
				}
				if mErr := os.MkdirAll(filepath.Dir(dest), 0o755); mErr != nil {
					w.t.Fatal(mErr)
				}
				if wErr := os.WriteFile(dest, []byte(f.Persisted), 0o644); wErr != nil {
					w.t.Fatal(wErr)
				}
				if f.MoveTo != nil && f.MoveTo.Absolute != f.Absolute {
					_ = os.Remove(f.Absolute)
					w.store.Relocate(f.Canonical, CanonicalPathKey(dest))
				}
			}
		}
		var tag string
		var provKey string
		switch f.Op {
		case EngineFileOpNoop:
			tag = w.store.Record(f.Canonical, f.After, nil, false)
		case EngineFileOpUpdate:
			key := f.Canonical
			if f.MoveTo != nil {
				key = CanonicalPathKey(f.MoveTo.Absolute)
			}
			tag = w.store.RecordEdit(key, f.Before, f.After)
			provKey = key
			w.store.ResetNoop(f.Canonical)
		case EngineFileOpDelete:
		}
		if f.ClipboardAfter != nil {
			w.store.CommitClipboard(f.ClipboardAfter)
		}
		if tag == "" {
			tag = FileHash(f.After)
		}
		txt := FormatStagedFileText(f, tag)
		if provKey != "" {
			if sl := SeenLinesFromBodyU32(txt); len(sl) > 0 {
				w.store.RecordSeenLinesU32(provKey, tag, sl)
			}
		}
		if txt != "" {
			out = append(out, txt)
		}
	}
	return strings.Join(out, EditResultSeparator), staged, nil
}

func numberedLines(count int) string {
	var b strings.Builder
	for i := 1; i <= count; i++ {
		fmt.Fprintf(&b, "line %d\n", i)
	}
	return b.String()
}

func allU32(n int) []uint32 {
	out := make([]uint32, n)
	for i := range n {
		out[i] = uint32(i + 1)
	}
	return out
}

func extractMismatchTag(t *testing.T, err *EditError) string {
	t.Helper()
	if err == nil {
		t.Fatal("expected mismatch error")
	}
	const needle = "current file hashes to #"
	idx := strings.Index(err.Error(), needle)
	if idx < 0 {
		t.Fatalf("missing current tag in %q", err.Error())
	}
	return err.Error()[idx+len(needle) : idx+len(needle)+4]
}

