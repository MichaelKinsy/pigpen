// upstream: crates/edit/src/modes/hashline/patcher.rs: "body_targets_single_anchor_needs_substantial_unique_token_bounded_content"
func TestBodyTargetsEvidenceChecks(t *testing.T) {
	file := []string{"let v0060 = 60;", "}", "foo(bar);", "dup_line();", "dup_line();"}
	if !bodyTargets([]string{"let v0060 = 60; // replay edit"}, file, 1, 1) {
		t.Fatal("expected match")
	}
	if bodyTargets([]string{"let v0058 = 58; // edit"}, file, 1, 1) {
		t.Fatal("stale anchor should fail")
	}
	if bodyTargets([]string{"let v0060 = 600;"}, []string{"let v0060 = 60"}, 1, 1) {
		t.Fatal("glued number prefix should fail")
	}
	if bodyTargets([]string{"process(items);"}, []string{"process(item"}, 1, 1) {
		t.Fatal("glued ident should fail")
	}
	if !bodyTargets([]string{"process(item); // edit"}, []string{"process(item"}, 1, 1) {
		t.Fatal("bounded token should pass")
	}
	if bodyTargets([]string{"}", "x();"}, file, 2, 2) {
		t.Fatal("short closer should fail")
	}
	if bodyTargets([]string{"dup_line(); // edit"}, file, 4, 4) {
		t.Fatal("duplicate line should fail")
	}
}

