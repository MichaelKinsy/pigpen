// UnwrapHashlineHeaderPath strips a strict `[path]` / `[path#XXXX]` hashline header wrapper.
// upstream: crates/edit/src/path_policy.rs:275
func UnwrapHashlineHeaderPath(target string) string {
	trimmed := strings.TrimRightFunc(target, unicode.IsSpace)
	if len(trimmed) < 2 || trimmed[0] != '[' || trimmed[len(trimmed)-1] != ']' {
		return target
	}
	inner := trimmed[1 : len(trimmed)-1]
	path := inner
	if idx := strings.LastIndexByte(inner, '#'); idx >= 0 {
		tag := inner[idx+1:]
		if len(tag) == 4 && isAllHex(tag) {
			path = inner[:idx]
		} else {
			return target
		}
	}
	if path == "" {
		return target
	}
	return path
}

func isAllHex(s string) bool {
	for i := range len(s) {
		b := s[i]
		if !((b >= '0' && b <= '9') || (b >= 'a' && b <= 'f') || (b >= 'A' && b <= 'F')) {
			return false
		}
	}
	return true
}

// addressEditTarget classifies an unwrapped display target using omp's PathPolicy::address rules.
// upstream: crates/edit/src/path_policy.rs:121
func (d *DiskFileSource) addressEditTarget(display string) (urlTarget string, isURL bool, refused string) {
	raw := strings.TrimPrefix(display, "@")
	scheme, rest, ok := strings.Cut(raw, ":")
	if !ok {
		return "", false, ""
	}
	path, ok := strings.CutPrefix(rest, "/")
	if !ok {
		return "", false, ""
	}
	listed := func(schemes []string) bool {
		for _, known := range schemes {
			if strings.EqualFold(known, scheme) {
				return true
			}
		}
		return false
	}
	if listed(d.URLSchemes) {
		if strings.HasPrefix(path, "/") {
			return raw, true, ""
		}
		if listed(d.URLAliasSchemes) {
			return scheme + "://" + path, true, ""
		}
		suggestion := strings.ToLower(scheme) + "://" + path
		return "", false, unknownURIEditTarget(display, suggestion)
	}
	isScheme := len(scheme) > 0 && isASCIIAlpha(scheme[0])
	for i := 1; i < len(scheme) && isScheme; i++ {
		b := scheme[i]
		if !isASCIIAlpha(b) && !(b >= '0' && b <= '9') && b != '+' && b != '.' && b != '-' {
			isScheme = false
		}
	}
	isLocal := len(scheme) == 1 || (strings.EqualFold(scheme, "file") && strings.HasPrefix(path, "/"))
	if !isScheme || isLocal {
		return "", false, ""
	}
	return "", false, unknownURIEditTarget(display, "")
}

func isASCIIAlpha(b byte) bool {
	return (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z')
}

// unknownURIEditTarget formats omp's exact refusal for URI-like edit targets.
// upstream: crates/edit/src/path_policy.rs:263
func unknownURIEditTarget(display, suggestion string) string {
	hint := ""
	if suggestion != "" {
		hint = fmt.Sprintf(" Did you mean '%s'?", suggestion)
	}
	return fmt.Sprintf(
		"Unknown URI-like edit target '%s'.%s Prefix the path with './' to edit it as a filesystem path.",
		display, hint,
	)
}

// expandEditPath ports crates/edit/src/path_policy.rs:340 (leading `:`, `@`, Unicode space
// folding, `file://` percent-decoding, Windows verbatim strip, and `~` expansion).
// upstream: crates/edit/src/path_policy.rs:340
func expandEditPath(value, homeDir string) string {
	if strings.HasPrefix(value, ":") {
		rest := value[1:]
		if strings.HasPrefix(rest, "/") ||
			strings.HasPrefix(rest, `\`) ||
			strings.HasPrefix(rest, "~") ||
			strings.HasPrefix(rest, "./") ||
			strings.HasPrefix(rest, "../") ||
			hasPathRoot(rest) {
			value = rest
		}
	}
	if strings.HasPrefix(value, "@") {
		rest := value[1:]
		if strings.HasPrefix(rest, "/") ||
			strings.HasPrefix(rest, `\`) ||
			rest == "~" ||
			strings.HasPrefix(rest, "~/") ||
			hasPathRoot(rest) {
			value = rest
		}
	}
	// Fold Unicode space separators (NBSP, U+2000..U+200A, U+202F, U+205F, U+3000) to ASCII space.
	var b strings.Builder
	folded := false
	for _, r := range value {
		if r == '\u00a0' || (r >= '\u2000' && r <= '\u200a') || r == '\u202f' || r == '\u205f' || r == '\u3000' {
			if !folded {
				b.Grow(len(value))
				folded = true
			}
			b.WriteByte(' ')
		} else if folded {
			b.WriteRune(r)
		}
	}
	if folded {
		// Re-run cleanly from start if we noticed a unicode space mid-string.
		var out strings.Builder
		out.Grow(len(value))
		for _, r := range value {
			if r == '\u00a0' || (r >= '\u2000' && r <= '\u200a') || r == '\u202f' || r == '\u205f' || r == '\u3000' {
				out.WriteByte(' ')
			} else {
				out.WriteRune(r)
			}
		}
		value = out.String()
	}
	if len(value) >= 7 && strings.EqualFold(value[:7], "file://") {
		rest := value[7:]
		if decoded, err := url.PathUnescape(rest); err == nil {
			value = decoded
		}
	}
	if rest, ok := strings.CutPrefix(value, `\\?\`); ok {
		if len(rest) >= 4 && strings.EqualFold(rest[:4], `UNC\`) {
			value = `\\` + rest[4:]
		} else if hasPathRoot(rest) {
			value = rest
		}
	}
	home := homeDir
	if home == "" {
		if h, err := os.UserHomeDir(); err == nil {
			home = h
		}
	}
	if home != "" {
		if value == "~" {
			return home
		}
		if rest, ok := strings.CutPrefix(value, "~/"); ok {
			return filepath.Join(home, rest)
		}
		if rest, ok := strings.CutPrefix(value, `~\`); ok {
			return filepath.Join(home, rest)
		}
		if rest, ok := strings.CutPrefix(value, "~"); ok {
			return filepath.Join(home, rest)
		}
	}
	return value
}

func (d *DiskFileSource) Resolve(authored string) (Resolved, *EditError) {
	display := UnwrapHashlineHeaderPath(authored)
	if urlTarget, isURL, refused := d.addressEditTarget(display); refused != "" {
		return Resolved{}, ApplyError(refused)
	} else if isURL {
		if d.URLResolver != nil {
			if res, handled, err := d.URLResolver(urlTarget); handled || err != nil {
				return res, err
			}
		}
		return Resolved{}, ApplyError(fmt.Sprintf("Unknown internal URL: %s", urlTarget))
	} else if d.URLResolver != nil {
		// Allow custom test URLResolvers when URLSchemes wasn't populated.
		if res, handled, err := d.URLResolver(display); handled || err != nil {
			return res, err
		}
	}
	target := expandEditPath(display, d.HomeDir)
	if target != "" && strings.Trim(target, "/") == "" {
		return Resolved{Absolute: filepath.Clean(d.WorkDir), Display: display}, nil
	}
	abs := target
	if !filepath.IsAbs(abs) {
		abs = filepath.Join(d.WorkDir, abs)
	}
	abs = filepath.Clean(abs)
	return Resolved{Absolute: abs, Display: display}, nil
}

func (d *DiskFileSource) Exists(absolute string) bool {
	_, err := os.Stat(absolute)
	return err == nil
}

func (d *DiskFileSource) AllowTagPathRecovery(authored, recoveredAbs string) bool {
	display := UnwrapHashlineHeaderPath(authored)
	if _, isURL, refused := d.addressEditTarget(display); isURL || refused != "" {
		return false
	}
	if len(d.PlanWritableRoots) == 0 {
		return false
	}
	target := CanonicalPathKey(recoveredAbs)
	for _, root := range d.PlanWritableRoots {
		cr := CanonicalPathKey(root)
		if target == cr || strings.HasPrefix(target, cr+string(filepath.Separator)) {
			return true
		}
	}
	return false
}

// specialFileKind returns omp's description for non-regular, non-directory files.
// upstream: crates/edit/src/files.rs:112
func specialFileKind(mode os.FileMode) string {
	if mode.IsRegular() || mode.IsDir() {
		return ""
	}
	if mode&os.ModeCharDevice != 0 {
		return "character device"
	}
	if mode&os.ModeDevice != 0 {
		return "block device"
	}
	if mode&os.ModeNamedPipe != 0 {
		return "FIFO"
	}
	if mode&os.ModeSocket != 0 {
		return "socket"
	}
	return "special file"
}

func (d *DiskFileSource) TryRead(resolved Resolved) (*FileRead, *EditError) {
	info, err := os.Stat(resolved.Absolute)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, IOError(resolved.Absolute, err, false)
	}
	if kind := specialFileKind(info.Mode()); kind != "" {
		return nil, ApplyError(fmt.Sprintf("Cannot edit '%s': it is a %s, not a regular file or directory.", resolved.Display, kind))
	}
	data, err := os.ReadFile(resolved.Absolute)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, IOError(resolved.Absolute, err, false)
	}
	if d.BlockAutoGenerated {
		head := data
		if len(head) > 1024 {
			head = head[:1024]
		}
		if msg := AutoGeneratedMessage(resolved.Display, head); msg != "" {
			return nil, ApplyError(msg)
		}
	}
	if !utf8.Valid(data) {
		validUpTo := 0
		for validUpTo < len(data) {
			r, size := utf8.DecodeRune(data[validUpTo:])
			if r == utf8.RuneError && size == 1 {
				break
			}
			validUpTo += size
		}
		return nil, InvalidUtf8Error(resolved.Display, validUpTo)
	}
	raw := string(data)
	isNotebook := IsNotebookPath(resolved.Absolute)
	var bom, normalized string
	var ending LineEnding
	if isNotebook {
		editable, nbErr := NotebookToEditableText(raw, resolved.Display)
		if nbErr != nil {
			return nil, ApplyError(nbErr.Error())
		}
		bom = ""
		normalized = NormalizeToLF(editable)
		ending = LineEndingLF
	} else {
		var body string
		bom, body = StripBOM(raw)
		ending = DetectLineEnding(body)
		normalized = NormalizeToLF(body)
	}
	return &FileRead{
		Resolved:   resolved,
		Canonical:  CanonicalPathKey(resolved.Absolute),
		Raw:        raw,
		BOM:        bom,
		Ending:     ending,
		Text:       normalized,
		IsNotebook: isNotebook,
	}, nil
}

