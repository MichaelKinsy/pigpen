// StagePatch stages every parsed hashline section atomically without writing to disk.
// upstream: crates/edit/src/modes/hashline/patcher.rs:835
func StagePatch(patch *Patch, rawInput string, files FileSource, store *Store, opts StageOptions) ([]StagedFile, *EditError) {
	var clipboard *Clipboard
	if store != nil {
		clipboard = store.StartBatchClipboard()
	} else {
		clipboard = &Clipboard{}
	}
	staged := make([]StagedFile, 0, len(patch.Sections))
	canonicalPaths := make(map[string]string, len(patch.Sections))
	var replies []string

	for _, original := range patch.Sections {
		item, err := stageSection(original, opts, files, store, clipboard, canonicalPaths)
		if err == nil {
			staged = append(staged, item)
			continue
		}
		if err.Reason == RejectionUnseenLines {
			replies = append(replies, err.Message)
			continue
		}
		if len(replies) == 0 {
			return nil, err
		}
		if err.Reason != RejectionNone {
			replies = append(replies, fmt.Sprintf("[%s]: %s", original.Path, err.Error()))
		}
	}
	if len(replies) > 0 {
		return nil, RejectedError(RejectionUnseenLines, strings.Join(replies, "\n\n"))
	}

	// No-op check & escalation.
	for i := range staged {
		if staged[i].Op != EngineFileOpNoop {
			continue
		}
		var count uint32 = 1
		escalate := false
		if store != nil {
			count, escalate = store.RecordNoop(staged[i].Canonical, PayloadHash(rawInput))
		}
		if len(patch.Sections) != 1 {
			msg := NoChangeDiagnostic(staged[i].Display)
			if escalate {
				msg = NoChangeLoopDiagnostic(staged[i].Display, count)
			}
			return nil, RejectedError(RejectionNoChange, msg)
		}
		if escalate {
			return nil, RejectedError(RejectionNoChange, NoChangeLoopDiagnostic(patch.Sections[0].Path, count))
		}
		staged[i].TextOverride = NoChangeDiagnostic(patch.Sections[0].Path)
		staged[i].HasTextOverride = true
		break
	}
	return staged, nil
}

func stageSection(
	original *PatchSection,
	opts StageOptions,
	files FileSource,
	store *Store,
	clipboard *Clipboard,
	canonicalPaths map[string]string,
) (StagedFile, *EditError) {
	parsed, err := parseWithRangeDiagnostics(original, files)
	if err != nil {
		return StagedFile{}, err
	}
	initial, err := files.Resolve(original.Path)
	if err != nil {
		return StagedFile{}, err
	}
	section := original
	resolved := initial
	if recSec, recRes, recErr := recoverTarget(original, initial, files, store); recErr != nil {
		return StagedFile{}, recErr
	} else if recSec != nil {
		section = recSec
		resolved = *recRes
	}

	undecodableDelete := original.HasHash && parsed.FileOp != nil && parsed.FileOp.Kind == FileOpDelete
	read, err := files.TryRead(resolved)
	if err != nil {
		if err.IsInvalidUtf8() && undecodableDelete {
			read = nil
		} else {
			return StagedFile{}, err
		}
	}
	if read == nil {
		if undecodableDelete && files.Exists(resolved.Absolute) {
			return undecodableDeleteStaged(section, resolved, original.Path, original.FileHash, parsed.Warnings, canonicalPaths, clipboard)
		}
		return StagedFile{}, RejectedError(
			RejectionFileNotFound,
			fmt.Sprintf("File not found: %s. Use the write tool to create new files.", section.Path),
		)
	}

	// A section with no tag (missing or placeholder like #AUTO) never applies.
	if !original.HasHash {
		return StagedFile{}, mismatchForSection(section, read.Canonical, read.Text, "", store)
	}
	tag := original.FileHash

	if prev, dup := canonicalPaths[read.Canonical]; dup {
		return StagedFile{}, ApplyError(fmt.Sprintf(
			"Multiple hashline sections resolve to the same file (%s and %s). Merge their ops under one header before applying.",
			prev, original.Path,
		))
	}
	canonicalPaths[read.Canonical] = original.Path

	var moveTo *Resolved
	if parsed.FileOp != nil && parsed.FileOp.Kind == FileOpMove {
		dest, dErr := files.Resolve(parsed.FileOp.Dest)
		if dErr != nil {
			return StagedFile{}, dErr
		}
		if CanonicalPathKey(dest.Absolute) == read.Canonical {
			return StagedFile{}, ApplyError(fmt.Sprintf("MV destination is the same as %s.", section.Path))
		}
		moveTo = &dest
	}

	applied, err := applyWithRecovery(
		section,
		read.Canonical,
		read.Text,
		parsed.Edits,
		clipboard,
		store,
		opts.EnforceSeenLines,
		opts.MaxColumns,
	)
	if err != nil {
		return StagedFile{}, err
	}

	// A REM section's cuts only fill registers; the file is deleted whole.
	if parsed.FileOp != nil && parsed.FileOp.Kind == FileOpDelete {
		applied.Text = read.Text
		applied.FirstChangedLine = 0
	}

	warnings := slices.Clone(parsed.Warnings)
	if section.Path != original.Path {
		warnings = append(warnings, PathRecoveredFromTagMessage(original.Path, section.Path, tag))
	}
	warnings = append(warnings, applied.Warnings...)

	engineOp := EngineFileOpUpdate
	if parsed.FileOp != nil && parsed.FileOp.Kind == FileOpDelete {
		engineOp = EngineFileOpDelete
	} else if applied.Text == read.Text && parsed.FileOp == nil {
		engineOp = EngineFileOpNoop
	}

	diffOut := GenerateDiffStringForPath(read.Text, applied.Text, 2, false, section.Path)
	firstChanged := applied.FirstChangedLine
	if firstChanged == 0 {
		firstChanged = diffOut.FirstChangedLine
	}

	var persisted string
	hasPersisted := false
	if engineOp != EngineFileOpDelete && engineOp != EngineFileOpNoop {
		var pErr *EditError
		persisted, pErr = read.Persist(applied.Text)
		if pErr != nil {
			return StagedFile{}, pErr
		}
		hasPersisted = true
	}
	beforePreview := make([]string, len(applied.BlockResolutions))
	for i, br := range applied.BlockResolutions {
		beforePreview[i] = FormatBlockResolution(br)
	}

	return StagedFile{
		Display:          section.Path,
		Absolute:         read.Resolved.Absolute,
		Canonical:        read.Canonical,
		Op:               engineOp,
		MoveTo:           moveTo,
		Existed:          true,
		BeforeRaw:        read.Raw,
		HasBeforeRaw:     true,
		Before:           read.Text,
		After:            applied.Text,
		Persisted:        persisted,
		HasPersisted:     hasPersisted,
		Diff:             diffOut.Diff,
		FirstChangedLine: firstChanged,
		BeforePreview:    beforePreview,
		Warnings:         warnings,
		RecordSnapshot:   true,
		ClipboardAfter:   clipboard.Fork(),
	}, nil
}

func undecodableDeleteStaged(
	section *PatchSection,
	resolved Resolved,
	originalPath, tag string,
	warnings []string,
	canonicalPaths map[string]string,
	clipboard *Clipboard,
) (StagedFile, *EditError) {
	w := slices.Clone(warnings)
	if section.Path != originalPath {
		w = append(w, PathRecoveredFromTagMessage(originalPath, section.Path, tag))
	}
	canonical := CanonicalPathKey(resolved.Absolute)
	if prev, dup := canonicalPaths[canonical]; dup {
		return StagedFile{}, ApplyError(fmt.Sprintf(
			"Multiple hashline sections resolve to the same file (%s and %s). Merge their ops under one header before applying.",
			prev, originalPath,
		))
	}
	canonicalPaths[canonical] = originalPath
	return StagedFile{
		Display:        section.Path,
		Absolute:       resolved.Absolute,
		Canonical:      canonical,
		Op:             EngineFileOpDelete,
		Existed:        true,
		Warnings:       w,
		RecordSnapshot: true,
		ClipboardAfter: clipboard.Fork(),
	}, nil
}

// FormatStagedFileText renders the model-facing output for one completed staged file.
// upstream: crates/edit/src/session.rs:515
func FormatStagedFileText(file *StagedFile, responseTag string) string {
	if file.HasTextOverride {
		return file.TextOverride
	}
	headerPath := file.Display
	if file.MoveTo != nil {
		headerPath = file.MoveTo.Display
	}
	header := FormatHeader(headerPath, responseTag)

	var body string
	if file.Op == EngineFileOpDelete {
		body = fmt.Sprintf("Deleted %s", file.Display)
	} else {
		preview := BuildCompactDiffPreview(file.Diff, ResponseAddedRunContextLines).Preview
		var lines []string
		lines = append(lines, header)
		lines = append(lines, file.BeforePreview...)
		if file.MoveTo != nil {
			if filepath.Dir(file.MoveTo.Absolute) == filepath.Dir(file.Absolute) {
				lines = append(lines, fmt.Sprintf("Moved to %s", file.MoveTo.Display))
			} else {
				lines = append(lines, fmt.Sprintf("Moved to %s", dirs.StandardizeMacOSPath(file.MoveTo.Absolute)))
			}
		}
		if preview != "" {
			lines = append(lines, preview)
		}
		lines = append(lines, file.AfterPreview...)
		nonEmpty := lines[:0]
		for _, l := range lines {
			if l != "" {
				nonEmpty = append(nonEmpty, l)
			}
		}
		body = strings.Join(nonEmpty, "\n")
	}

	var nonEmptyWarnings []string
	for _, w := range file.Warnings {
		if w != "" {
			nonEmptyWarnings = append(nonEmptyWarnings, w)
		}
	}
	if len(nonEmptyWarnings) == 0 {
		return body
	}
	return fmt.Sprintf("%s\n\nWarnings:\n%s", body, strings.Join(nonEmptyWarnings, "\n"))
}

// PruneSnapshots drops oldText/newText when their combined UTF-16 length exceeds MaxEditSnapshotTextChars.
// upstream: crates/edit/src/session.rs:566
func PruneSnapshots(oldText string, hasOld bool, newText string, hasNew bool) (string, bool, string, bool, bool) {
	size := 0
	if hasOld {
		size += utf16Len(oldText)
	}
	if hasNew {
		size += utf16Len(newText)
	}
	if size <= MaxEditSnapshotTextChars {
		return oldText, hasOld, newText, hasNew, false
	}
	return "", false, "", false, true
}

