// Persist restores BOM and line endings to afterLF, or re-serializes `.ipynb` notebooks.
// upstream: crates/edit/src/files.rs:52
func (r *FileRead) Persist(afterLF string) (string, *EditError) {
	if r.IsNotebook {
		serialized, err := SerializeEditedNotebookText(r.Raw, true, afterLF, r.Resolved.Display)
		if err != nil {
			return "", ApplyError(err.Error())
		}
		return serialized, nil
	}
	return r.BOM + RestoreLineEndings(afterLF, r.Ending), nil
}

