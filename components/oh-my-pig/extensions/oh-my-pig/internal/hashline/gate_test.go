package hashline

import (
	"fmt"
	"path/filepath"
	"strings"
	"testing"

	sdk "github.com/MichaelKinsy/PiG/extensions/sdk"
	"github.com/MichaelKinsy/pigpen/oh-my-pig/internal/gate"
)

// Tests for CheckStagedGate including plan-mode refusals, atomic multi-file blocking,
// and the two bypasses identified in review: lone \r hiding a second section, and MV + tab.

func TestGateChecksAllSectionsAndBlocksBypasses(t *testing.T) {
	t.Cleanup(gate.ResetForTests)

	dir := t.TempDir()
	w := newTestWorkspace(t)
	w.dir = dir
	planFile := w.writeFile("plan.md", "# Plan\n")
	_ = w.writeFile("src.go", "package main\n")
	dstFile := filepath.Join(dir, "outside.go")

	planTag := w.snapshot("plan.md", "# Plan\n", nil)
	srcTag := w.snapshot("src.go", "package main\n", nil)

	planKey := CanonicalPathKey(planFile)
	var seenReqs []gate.Request
	gate.SetPolicy(func(_ sdk.Context, r gate.Request) error {
		seenReqs = append(seenReqs, r)
		if r.Op == gate.OpDelete {
			return fmt.Errorf("Plan mode: deleting files is not allowed.")
		}
		if r.Op == gate.OpMove {
			return fmt.Errorf("Plan mode: renaming files is not allowed.")
		}
		if CanonicalPathKey(r.Path) != planKey {
			return fmt.Errorf("Plan mode: the working tree is read-only.")
		}
		return nil
	})

	fileSrc := &DiskFileSource{WorkDir: dir, BlockAutoGenerated: true}

	// 1. Allowed single edit to plan.md passes gate.
	seenReqs = nil
	staged, err := StageInput(fmt.Sprintf("[plan.md#%s]\nPUT 1.=1:\n+# Updated\n", planTag), fileSrc, w.store, StageOptions{})
	if err != nil {
		t.Fatalf("stage plan.md: %v", err)
	}
	if gErr := CheckStagedGate(sdk.Context{}, staged, nil); gErr != nil {
		t.Fatalf("expected plan.md edit allowed, got %v", gErr)
	}
	if len(seenReqs) != 1 || seenReqs[0].Op != gate.OpEdit || seenReqs[0].Path != planFile {
		t.Fatalf("reqs=%+v", seenReqs)
	}

	// 2. Multi-file edit where section 1 is allowed (plan.md) and section 2 is refused (src.go):
	// whole call refused before any write.
	seenReqs = nil
	staged, err = StageInput(fmt.Sprintf("[plan.md#%s]\nPUT 1.=1:\n+# Updated\n[src.go#%s]\nPUT 1.=1:\n+package hacked\n", planTag, srcTag), fileSrc, w.store, StageOptions{})
	if err != nil {
		t.Fatalf("stage multi: %v", err)
	}
	if gErr := CheckStagedGate(sdk.Context{}, staged, nil); gErr == nil || gErr.Kind() != "plan_mode" {
		t.Fatalf("expected plan_mode refusal, got %v", gErr)
	}

	// 3. REM passes OpDelete to gate and is refused.
	seenReqs = nil
	staged, err = StageInput(fmt.Sprintf("[plan.md#%s]\nREM\n", planTag), fileSrc, w.store, StageOptions{})
	if err != nil {
		t.Fatalf("stage REM: %v", err)
	}
	if gErr := CheckStagedGate(sdk.Context{}, staged, nil); gErr == nil || !strings.Contains(gErr.Error(), "deleting files is not allowed") {
		t.Fatalf("expected REM refusal, got %v", gErr)
	}
	if len(seenReqs) != 1 || seenReqs[0].Op != gate.OpDelete {
		t.Fatalf("expected OpDelete, got %+v", seenReqs)
	}

	// 4. Bypass #1: MV followed by a TAB (`MV\toutside.go`) must parse as FileOpMove
	// and reach gate.Check with OpMove and resolved Dest.
	seenReqs = nil
	staged, err = StageInput(fmt.Sprintf("[plan.md#%s]\nMV\toutside.go\n", planTag), fileSrc, w.store, StageOptions{})
	if err != nil {
		t.Fatalf("stage MV+tab: %v", err)
	}
	if gErr := CheckStagedGate(sdk.Context{}, staged, nil); gErr == nil || !strings.Contains(gErr.Error(), "renaming files is not allowed") {
		t.Fatalf("expected MV+tab refusal, got %v", gErr)
	}
	if len(seenReqs) != 1 || seenReqs[0].Op != gate.OpMove || seenReqs[0].Dest != dstFile {
		t.Fatalf("expected OpMove with Dest=%s, got %+v", dstFile, seenReqs)
	}

	// Also test a policy that allows OpMove on source but rejects OpWrite on destination.
	gate.SetPolicy(func(_ sdk.Context, r gate.Request) error {
		if r.Op == gate.OpWrite && CanonicalPathKey(r.Path) != planKey {
			return fmt.Errorf("destination outside sandbox: %s", r.Path)
		}
		return nil
	})
	if gErr := CheckStagedGate(sdk.Context{}, staged, nil); gErr == nil || !strings.Contains(gErr.Error(), "destination outside sandbox") {
		t.Fatalf("expected destination refusal, got %v", gErr)
	}

	// 5. Bypass #2: lone \r hiding a second section.
	// Case A: lone \r before header on its own line (`\r[src.go#TAG]`) -> rejected by parser
	// as malformed header row, never silently mutating src.go.
	_, err = StageInput(fmt.Sprintf("[plan.md#%s]\nPUT 1.=1:\n+# ok\n\r[src.go#%s]\nPUT 1.=1:\n+package hacked\n", planTag, srcTag), fileSrc, w.store, StageOptions{})
	if err == nil {
		t.Fatal("expected lone-CR header-shaped row to fail parse")
	}

	// Case B: lone \r inline inside a payload row (`+ok\r[src.go#TAG]`) -> stays literal content
	// of plan.md, NEVER opens a section for src.go; staged has only plan.md.
	staged, err = StageInput(fmt.Sprintf("[plan.md#%s]\nPUT 1.=1:\n+# ok\r[src.go#%s]\n", planTag, srcTag), fileSrc, w.store, StageOptions{})
	if err != nil {
		t.Fatalf("stage inline lone-CR: %v", err)
	}
	if len(staged) != 1 || staged[0].Absolute != planFile {
		t.Fatalf("inline lone-CR must not create a second section, got %+v", staged)
	}

	// Case C: CRLF before second section -> parsed as second section and refused by gate.
	gate.SetPolicy(func(_ sdk.Context, r gate.Request) error {
		if CanonicalPathKey(r.Path) != planKey {
			return fmt.Errorf("Plan mode: the working tree is read-only.")
		}
		return nil
	})
	staged, err = StageInput(fmt.Sprintf("[plan.md#%s]\r\nPUT 1.=1:\r\n+# ok\r\n[src.go#%s]\r\nPUT 1.=1:\r\n+package hacked\r\n", planTag, srcTag), fileSrc, w.store, StageOptions{})
	if err != nil {
		t.Fatalf("stage CRLF two sections: %v", err)
	}
	if gErr := CheckStagedGate(sdk.Context{}, staged, nil); gErr == nil || gErr.Kind() != "plan_mode" {
		t.Fatalf("expected CRLF second section refused by gate, got %v", gErr)
	}
}
