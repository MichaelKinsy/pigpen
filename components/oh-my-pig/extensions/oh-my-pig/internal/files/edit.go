// executeEdit implements omp's hashline `edit` tool.
// Staging runs across every section atomically before any file is written.
// Every parsed section and move destination is checked against internal/gate
// before the first write.
// upstream: packages/coding-agent/src/edit/index.ts, crates/edit/src/session.rs
func executeEdit(ctx sdk.Context, store *hashline.Store, cwd, input string) (sdk.ToolResult, error) {
	if store == nil {
		store = hashline.ForSession(ctx)
	} else if s := hashline.ForSession(ctx); hashline.HasSessionID(ctx) {
		// Live sessions share the single per-session hashline store across
		// read, grep, ast, lsp, and edit.
		store = s
	}
	urlCtx := urls.Context{SDK: ctx, Cwd: cwd}
	urlSchemes := urls.Schemes()
	var urlAliasSchemes []string
	for _, scheme := range urlSchemes {
		if spec, ok := urls.LookupSpec(scheme); ok && spec.SingleSlashAlias {
			urlAliasSchemes = append(urlAliasSchemes, scheme)
		}
	}
	urlMap := make(map[string]string) // canonical abs path -> original URL for gate.Request.URL
	fileSrc := &hashline.DiskFileSource{
		WorkDir:            cwd,
		BlockAutoGenerated: true,
		PlanWritableRoots:  urls.SandboxRoots(urlCtx),
		URLSchemes:         urlSchemes,
		URLAliasSchemes:    urlAliasSchemes,
		URLResolver: func(authored string) (hashline.Resolved, bool, *hashline.EditError) {
			return resolveEditURLTarget(ctx, cwd, authored, urlMap)
		},
	}

	opts := hashline.StageOptions{
		EnforceSeenLines:   true,
		MaxColumns:         512, // omp default: grep's 512-byte cap
		BlockAutoGenerated: true,
	}

	staged, stageErr := hashline.StageInput(input, fileSrc, store, opts)
	if stageErr != nil {
		// Return nil Go error with IsError:true so PiG keeps Details ({diff, errorKind}).
		// Returning a non-nil error causes PiG's errorToolResult to discard Details.
		// upstream: packages/coding-agent/src/edit/index.ts:625-631
		return sdk.ToolResult{
			Content: stageErr.Error(),
			Details: map[string]any{
				"diff":      "",
				"errorKind": stageErr.Kind(),
			},
			IsError: true,
		}, nil
	}

	// Enforce restricting mode (plan mode / gate.Policy) across EVERY staged section
	// BEFORE the first write, using the parsed operations and resolved absolute targets.
	// upstream: crates/edit/src/session.rs:352, crates/edit/src/path_policy.rs:176
	if gateErr := hashline.CheckStagedGate(ctx, staged, urlMap); gateErr != nil {
		return sdk.ToolResult{
			Content: gateErr.Error(),
			Details: map[string]any{
				"diff":      "",
				"errorKind": gateErr.Kind(),
			},
			IsError: true,
		}, nil
	}

	results := make([]string, 0, len(staged))
	perFile := make([]map[string]any, 0, len(staged))

	for i := range staged {
		file := &staged[i]
		var writtenText string

		if file.Op != hashline.EngineFileOpNoop {
			queuePath := file.Absolute
			err := withMutationQueue(ctx, queuePath, func() error {
				journaled := isRecordFileChangeActive(ctx)
				readSnap := func(p string) (*string, bool) {
					if !journaled {
						return nil, false
					}
					if b, rErr := os.ReadFile(p); rErr == nil {
						s := string(b)
						return &s, true
					} else if errors.Is(rErr, os.ErrNotExist) {
						return nil, true
					}
					return nil, false
				}
				switch file.Op {
				case hashline.EngineFileOpDelete:
					var beforeSnap *string
					beforeOK := false
					if journaled {
						if file.HasBeforeRaw {
							// Reuse raw bytes already read during staging.
							s := file.BeforeRaw
							beforeSnap = &s
							beforeOK = true
						} else {
							beforeSnap, beforeOK = readSnap(file.Absolute)
						}
					}
					if err := os.Remove(file.Absolute); err != nil {
						return err
					}
					if beforeOK {
						runRecordFileChangeHook(ctx, "edit", file.Absolute, beforeSnap, nil)
					}
					return nil
				case hashline.EngineFileOpUpdate, hashline.EngineFileOpCreate:
					if !file.HasPersisted {
						return fmt.Errorf("edit %s request omitted content", file.Op)
					}
					if file.MoveTo != nil {
						var srcBefore *string
						srcOK := false
						var dstBefore *string
						dstOK := false
						if journaled {
							if file.HasBeforeRaw {
								s := file.BeforeRaw
								srcBefore = &s
								srcOK = true
							} else {
								srcBefore, srcOK = readSnap(file.Absolute)
							}
							dstBefore, dstOK = readSnap(file.MoveTo.Absolute)
						}
						if err := moveEditedFile(file.Absolute, file.MoveTo.Absolute, file.Persisted); err != nil {
							return err
						}
						if srcOK {
							runRecordFileChangeHook(ctx, "edit", file.Absolute, srcBefore, nil)
						}
						if dstOK {
							after := file.Persisted
							runRecordFileChangeHook(ctx, "edit", file.MoveTo.Absolute, dstBefore, &after)
						}
						return nil
					}
					// Capture pre-write bytes for update so we can detect writes that did
					// not land on disk (matching packages/coding-agent/src/edit/index.ts:875-925).
					var preWriteBytes []byte
					hasPreWrite := false
					var journalBefore *string
					journalBeforeOK := false
					if file.Op == hashline.EngineFileOpUpdate {
						if b, rErr := os.ReadFile(file.Absolute); rErr == nil {
							preWriteBytes = b
							hasPreWrite = true
							if journaled {
								s := string(b)
								journalBefore = &s
								journalBeforeOK = true
							}
						} else if !errors.Is(rErr, os.ErrNotExist) {
							return rErr
						} else if journaled {
							journalBefore = nil
							journalBeforeOK = true
						}
					} else if file.Op == hashline.EngineFileOpCreate {
						if journaled {
							if !file.Existed {
								journalBefore = nil
								journalBeforeOK = true
							} else if file.HasBeforeRaw {
								s := file.BeforeRaw
								journalBefore = &s
								journalBeforeOK = true
							} else {
								journalBefore, journalBeforeOK = readSnap(file.Absolute)
							}
						}
						if mErr := os.MkdirAll(filepath.Dir(file.Absolute), 0o755); mErr != nil {
							return mErr
						}
					}
					if err := os.WriteFile(file.Absolute, []byte(file.Persisted), 0o644); err != nil {
						return err
					}
					if hasPreWrite {
						postWriteBytes, pErr := os.ReadFile(file.Absolute)
						if pErr != nil && !errors.Is(pErr, os.ErrNotExist) {
							return pErr
						}
						if pErr == nil && bytes.Equal(postWriteBytes, preWriteBytes) && !bytes.Equal([]byte(file.Persisted), preWriteBytes) {
							return fmt.Errorf("edit appeared successful but file content did not change on disk: %s", file.Display)
						}
					}
					if journalBeforeOK {
						after := file.Persisted
						runRecordFileChangeHook(ctx, "edit", file.Absolute, journalBefore, &after)
					}
					writtenText = file.Persisted
					return nil
				}
				return nil
			})
			if err != nil {
				if len(staged) > 1 {
					resultPath := dirs.StandardizeMacOSPath(file.Absolute)
					if file.MoveTo != nil {
						resultPath = dirs.StandardizeMacOSPath(file.MoveTo.Absolute)
					}
					errEntry := map[string]any{
						"path":             resultPath,
						"diff":             "",
						"op":               file.Op.WireOp(),
						"isError":          true,
						"errorText":        err.Error(),
						"displayErrorText": err.Error(),
					}
					perFile = append(perFile, errEntry)
					details := aggregateEditDetails(perFile)
					details["errorKind"] = string(hashline.ErrorKindWriteFailed)
					return sdk.ToolResult{
						Content: err.Error(),
						Details: details,
						IsError: true,
					}, nil
				}
				return sdk.ToolResult{
					Content: err.Error(),
					Details: map[string]any{
						"diff":      "",
						"errorKind": string(hashline.ErrorKindWriteFailed),
					},
					IsError: true,
				}, nil
			}
			if file.MoveTo != nil {
				writtenText = file.Persisted
			}
		}

		var tag string
		var provenanceKey string
		switch file.Op {
		case hashline.EngineFileOpDelete:
			if store != nil {
				store.Invalidate(file.Canonical)
			}
		case hashline.EngineFileOpNoop:
			if file.RecordSnapshot && store != nil {
				tag = store.Record(file.Canonical, file.After, nil, false)
			}
		case hashline.EngineFileOpCreate, hashline.EngineFileOpUpdate:
			destKey := file.Canonical
			if file.MoveTo != nil {
				destKey = hashline.CanonicalPathKey(file.MoveTo.Absolute)
				if store != nil {
					store.Relocate(file.Canonical, destKey)
				}
			}
			if file.RecordSnapshot && store != nil {
				if writtenText != "" && file.HasPersisted && writtenText != file.Persisted {
					_, body := hashline.StripBOM(writtenText)
					recorded := hashline.NormalizeToLF(body)
					if recorded != file.After {
						if file.MoveTo == nil {
							file.Warnings = append(file.Warnings, hashline.WriteDriftWarning(file.Display))
						}
						diffOut := hashline.GenerateDiffStringForPath(file.Before, recorded, 2, false, file.Display)
						file.Diff = diffOut.Diff
						file.FirstChangedLine = diffOut.FirstChangedLine
						file.After = recorded
					}
				}
				if file.Op == hashline.EngineFileOpUpdate {
					tag = store.RecordEdit(destKey, file.Before, file.After)
					provenanceKey = destKey
				} else {
					tag = store.Record(destKey, file.After, nil, false)
				}
			}
			if store != nil {
				store.ResetNoop(file.Canonical)
			}
		}
		if file.ClipboardAfter != nil && store != nil {
			store.CommitClipboard(file.ClipboardAfter)
		}

		if tag == "" {
			tag = hashline.FileHash(file.After)
		}
		secText := hashline.FormatStagedFileText(file, tag)
		if provenanceKey != "" && store != nil {
			seenLines := hashline.SeenLinesFromBodyU32(secText)
			if len(seenLines) > 0 {
				store.RecordSeenLinesU32(provenanceKey, tag, seenLines)
			}
		}

		var diagObj map[string]any
		if file.Op != hashline.EngineFileOpDelete && file.Op != hashline.EngineFileOpNoop {
			diagPath := file.Absolute
			if file.MoveTo != nil {
				diagPath = file.MoveTo.Absolute
			}
			if diag := runEditDiagnosticsHook(ctx, diagPath); diag != "" {
				secText += "\n" + diag
				diagObj = parseDiagnosticsDetail(diag)
			}
		}

		if secText != "" {
			results = append(results, secText)
		}

		// Build per-file Details matching packages/coding-agent/src/edit/index.ts:254
		// and crates/natives/src/edit.rs:746:
		// - `diff` carries omp's numbered diff format (+N|text, -N|text,  N|text), empty for delete
		// - `patch` carries the unified diff for PiG's ToolCard.Diff / kit.Diff (omitted for delete/noop)
		// - `path`, `move`, `sourcePath` are absolute paths
		var oldText string
		hasOld := file.Op != hashline.EngineFileOpCreate && file.HasBeforeRaw
		if hasOld {
			oldText = file.BeforeRaw
		}
		var newText string
		hasNew := false
		switch file.Op {
		case hashline.EngineFileOpDelete:
		case hashline.EngineFileOpNoop:
			if file.HasBeforeRaw {
				newText = file.BeforeRaw
				hasNew = true
			}
		default:
			newText = writtenText
			hasNew = true
		}

		var unifiedPatch string
		if file.Op != hashline.EngineFileOpDelete && file.Op != hashline.EngineFileOpNoop && file.Before != file.After {
			patchPath := file.Display
			if file.MoveTo != nil {
				patchPath = file.MoveTo.Display
			}
			unifiedPatch = generateUnifiedPatch(ctx, patchPath, oldText, newText)
		}

		oldText, hasOld, newText, hasNew, pruned := hashline.PruneSnapshots(oldText, hasOld, newText, hasNew)

		resultPath := dirs.StandardizeMacOSPath(file.Absolute)
		if file.MoveTo != nil {
			resultPath = dirs.StandardizeMacOSPath(file.MoveTo.Absolute)
		}
		diffField := file.Diff
		if file.Op == hashline.EngineFileOpDelete {
			diffField = ""
		}
		entry := map[string]any{
			"path": resultPath,
			"diff": diffField,
			"op":   file.Op.WireOp(),
		}
		if unifiedPatch != "" {
			entry["patch"] = unifiedPatch
		}
		if file.FirstChangedLine > 0 {
			entry["firstChangedLine"] = int(file.FirstChangedLine)
		}
		if file.MoveTo != nil {
			entry["move"] = dirs.StandardizeMacOSPath(file.MoveTo.Absolute)
			entry["sourcePath"] = dirs.StandardizeMacOSPath(file.Absolute)
		}
		if hasOld {
			entry["oldText"] = oldText
		}
		if hasNew {
			entry["newText"] = newText
		}
		if pruned {
			entry["snapshotsPruned"] = true
		}
		if diagObj != nil {
			entry["diagnostics"] = diagObj
			entry["meta"] = map[string]any{
				"diagnostics": map[string]any{
					"summary":  diagObj["summary"],
					"messages": diagObj["messages"],
				},
			}
		}
		perFile = append(perFile, entry)
	}

	details := aggregateEditDetails(perFile)
	return sdk.ToolResult{
		Content: strings.Join(results, hashline.EditResultSeparator),
		Details: details,
	}, nil
}

// resolveEditURLTarget resolves an internal URL target for edit, peeling write
// selectors (refusing line/partial selectors) and rejecting read-only / handler-written schemes.
// upstream: packages/coding-agent/src/edit/index.ts:751
func resolveEditURLTarget(ctx sdk.Context, cwd, authored string, urlMap map[string]string) (hashline.Resolved, bool, *hashline.EditError) {
	candidate := authored
	if rest, ok := strings.CutPrefix(candidate, "@"); ok && urls.CanHandle(rest) {
		candidate = rest
	}
	if !urls.CanHandle(candidate) {
		return hashline.Resolved{}, false, nil
	}
	target, peelErr := urls.PeelWriteSelector(candidate, "edit")
	if peelErr != nil {
		return hashline.Resolved{}, true, hashline.ApplyError(peelErr.Error())
	}
	u, err := urls.Parse(target)
	if err != nil {
		return hashline.Resolved{}, true, hashline.ApplyError(err.Error())
	}
	h, ok := urls.Lookup(u.Scheme)
	if !ok {
		return hashline.Resolved{}, true, hashline.ApplyError(fmt.Sprintf("Unknown internal URL: %s", candidate))
	}
	spec := h.Spec()
	if spec.Write == nil || spec.Write.Via != "file" || spec.Immutable {
		reason := "is read-only"
		if spec.Write != nil && spec.Write.Via == "handler" {
			reason = "is written through `write`, not edited"
		}
		return hashline.Resolved{}, true, hashline.ApplyError(fmt.Sprintf("%s %s", candidate, reason))
	}
	located, found, err := urls.Locate(urls.Context{SDK: ctx, Cwd: cwd}, target, urls.LocateOptions{Create: true})
	if err != nil {
		return hashline.Resolved{}, true, hashline.ApplyError(err.Error())
	}
	if !found || located == "" {
		return hashline.Resolved{}, true, hashline.ApplyError(fmt.Sprintf("No local file backs %s", candidate))
	}
	abs := resolveToCwd(located, cwd)
	urlMap[hashline.CanonicalPathKey(abs)] = target
	return hashline.Resolved{Absolute: abs, Display: target}, true, nil
}

// moveEditedFile writes content to dest, preserving POSIX permission bits (incl. setuid/exec)
// from src, then deletes src.
// upstream: packages/coding-agent/src/edit/index.ts:342-363, 827-837
func moveEditedFile(srcAbs, destAbs, content string) error {
	var srcMode os.FileMode
	hasMode := false
	if runtime.GOOS != "windows" {
		info, err := os.Stat(srcAbs)
		if err != nil {
			if !errors.Is(err, os.ErrPermission) {
				return err
			}
		} else {
			srcMode = info.Mode() & (os.ModePerm | os.ModeSetuid | os.ModeSetgid | os.ModeSticky)
			hasMode = true
		}
	}
	if err := os.MkdirAll(filepath.Dir(destAbs), 0o755); err != nil {
		return err
	}
	writePerm := os.FileMode(0o644)
	if hasMode {
		writePerm = srcMode & os.ModePerm
	}
	if err := os.WriteFile(destAbs, []byte(content), writePerm); err != nil {
		return err
	}
	if hasMode {
		if err := os.Chmod(destAbs, srcMode); err != nil && !errors.Is(err, os.ErrPermission) {
			return err
		}
	}
	if destAbs != srcAbs {
		if err := os.Remove(srcAbs); err != nil {
			return err
		}
	}
	return nil
}

// aggregateEditDetails builds omp's EditToolDetails shape for single-file and multi-file edits.
// upstream: packages/coding-agent/src/edit/index.ts:277
func aggregateEditDetails(perFile []map[string]any) map[string]any {
	if len(perFile) == 0 {
		return nil
	}
	if len(perFile) == 1 {
		out := make(map[string]any, len(perFile[0]))
		for k, v := range perFile[0] {
			out[k] = v
		}
		return out
	}
	var diffs []string
	var patches []string
	var firstChanged int
	var diagSummaries []string
	var diagMessages []string
	diagErrored := false
	for _, entry := range perFile {
		if d, ok := entry["diff"].(string); ok && d != "" {
			diffs = append(diffs, d)
		}
		if p, ok := entry["patch"].(string); ok && p != "" {
			patches = append(patches, p)
		}
		if firstChanged == 0 {
			if fcl, ok := entry["firstChangedLine"].(int); ok && fcl > 0 {
				firstChanged = fcl
			}
		}
		if diag, ok := entry["diagnostics"].(map[string]any); ok && diag != nil {
			if s, ok := diag["summary"].(string); ok && s != "" {
				diagSummaries = append(diagSummaries, s)
			}
			if msgs, ok := diag["messages"].([]string); ok {
				diagMessages = append(diagMessages, msgs...)
			}
			if e, ok := diag["errored"].(bool); ok && e {
				diagErrored = true
			}
		}
	}
	capped := capPerFileSnapshots(perFile)
	details := map[string]any{
		"diff":           strings.Join(diffs, "\n"),
		"perFileResults": capped,
	}
	if len(patches) > 0 {
		details["patch"] = strings.Join(patches, "")
	}
	if firstChanged > 0 {
		details["firstChangedLine"] = firstChanged
	}
	if len(diagMessages) > 0 || len(diagSummaries) > 0 {
		summary := strings.Join(diagSummaries, "; ")
		details["diagnostics"] = map[string]any{
			"summary":  summary,
			"messages": diagMessages,
			"errored":  diagErrored,
		}
		details["meta"] = map[string]any{
			"diagnostics": map[string]any{
				"summary":  summary,
				"messages": diagMessages,
			},
		}
	}
	return details
}

// capPerFileSnapshots shares the 32,768-char snapshot budget across multi-file entries.
// upstream: packages/coding-agent/src/edit/index.ts:315
func capPerFileSnapshots(entries []map[string]any) []map[string]any {
	remaining := hashline.MaxEditSnapshotTextChars
	out := make([]map[string]any, len(entries))
	for i, entry := range entries {
		oldStr, _ := entry["oldText"].(string)
		newStr, _ := entry["newText"].(string)
		kept := len([]rune(oldStr)) + len([]rune(newStr))
		if kept == 0 || kept <= remaining {
			remaining -= kept
			out[i] = entry
			continue
		}
		cp := make(map[string]any, len(entry))
		for k, v := range entry {
			if k == "oldText" || k == "newText" {
				continue
			}
			cp[k] = v
		}
		cp["snapshotsPruned"] = true
		out[i] = cp
	}
	return out
}
