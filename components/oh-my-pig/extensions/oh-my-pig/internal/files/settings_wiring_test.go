func TestFilesSettingsWiring_EditBlockAutoGenerated(t *testing.T) {
	prev := Setting
	t.Cleanup(func() { Setting = prev })

	dir := t.TempDir()
	path := filepath.Join(dir, "gen.pb.go")
	orig := "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\nvar X = 1\n"
	if err := os.WriteFile(path, []byte(orig), 0o644); err != nil {
		t.Fatal(err)
	}

	store := hashline.NewStore()
	readRes, err := executeReadWithCtx(sdk.Context{}, store, dir, "gen.pb.go")
	if err != nil {
		t.Fatalf("read failed: %v", err)
	}
	headerEnd := strings.IndexByte(readRes.Content, '\n')
	header := readRes.Content[:headerEnd]

	editInput := header + "\nPUT 3.=3:\n+var X = 2\n"

	// 1. Default (Setting == nil): blocks auto-generated file.
	Setting = nil
	res, err := executeEdit(sdk.Context{}, store, dir, editInput)
	if err != nil {
		t.Fatalf("edit err: %v", err)
	}
	if !res.IsError || !strings.Contains(strings.ToLower(res.Content), "auto-generated") {
		t.Fatalf("expected auto-generated block by default, got isError=%v content=%q", res.IsError, res.Content)
	}

	// 2. edit.blockAutoGenerated = false: allows editing auto-generated file.
	Setting = func(_ sdk.Context, key string) any {
		if key == "edit.blockAutoGenerated" {
			return false
		}
		return nil
	}
	res, err = executeEdit(sdk.Context{}, store, dir, editInput)
	if err != nil {
		t.Fatalf("edit err with blockAutoGenerated=false: %v", err)
	}
	if res.IsError {
		t.Fatalf("expected edit to succeed with blockAutoGenerated=false, got error: %s", res.Content)
	}
	gotBytes, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(gotBytes), "var X = 2") {
		t.Fatalf("expected updated file content, got %q", string(gotBytes))
	}

	// 3. write tool also honours edit.blockAutoGenerated = false (and blocks by default).
	Setting = nil
	newContent := "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\nvar X = 3\n"
	if _, err := executeWrite(sdk.Context{}, store, dir, "gen.pb.go", &newContent); err == nil {
		t.Fatalf("expected write to block auto-generated file by default")
	}
	Setting = func(_ sdk.Context, key string) any {
		if key == "edit.blockAutoGenerated" {
			return false
		}
		return nil
	}
	if _, err := executeWrite(sdk.Context{}, store, dir, "gen.pb.go", &newContent); err != nil {
		t.Fatalf("expected write to succeed with edit.blockAutoGenerated=false, got %v", err)
	}
}

func TestFilesSettingsWiring_EditEnforceSeenLines(t *testing.T) {
	prev := Setting
	t.Cleanup(func() { Setting = prev })

	dir := t.TempDir()
	path := filepath.Join(dir, "sample.txt")
	var lines []string
	for i := 1; i <= 20; i++ {
		lines = append(lines, fmt.Sprintf("line %d", i))
	}
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	store := hashline.NewStore()
	// Read only lines 1-3 (so line 18 is unseen).
	readRes, err := executeReadWithCtx(sdk.Context{}, store, dir, "sample.txt:1-3")
	if err != nil {
		t.Fatalf("read failed: %v", err)
	}
	header := readRes.Content[:strings.IndexByte(readRes.Content, '\n')]
	editInput := header + "\nPUT 18.=18:\n+line 18 edited\n"

	// 1. Default (Setting == nil): rejects unseen line 18.
	Setting = nil
	res, err := executeEdit(sdk.Context{}, store, dir, editInput)
	if err != nil {
		t.Fatalf("edit err: %v", err)
	}
	if !res.IsError {
		t.Fatalf("expected unseen-line rejection by default, got success: %s", res.Content)
	}

	// 2. edit.enforceSeenLines = false: permits editing unseen line 18.
	Setting = func(_ sdk.Context, key string) any {
		if key == "edit.enforceSeenLines" {
			return false
		}
		return nil
	}
	res, err = executeEdit(sdk.Context{}, store, dir, editInput)
	if err != nil {
		t.Fatalf("edit err with enforceSeenLines=false: %v", err)
	}
	if res.IsError {
		t.Fatalf("expected edit to succeed with enforceSeenLines=false, got error: %s", res.Content)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "line 18 edited") {
		t.Fatalf("expected line 18 updated, got %q", string(got))
	}
}

func TestFilesSettingsWiring_ReadDefaultLimitColumnsAndSpill(t *testing.T) {
	prev := Setting
	t.Cleanup(func() { Setting = prev })

	dir := t.TempDir()
	// 1. read.defaultLimit
	var many []string
	for i := 1; i <= 50; i++ {
		many = append(many, fmt.Sprintf("row %d", i))
	}
	if err := os.WriteFile(filepath.Join(dir, "many.txt"), []byte(strings.Join(many, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	Setting = func(_ sdk.Context, key string) any {
		if key == "read.defaultLimit" {
			return float64(10)
		}
		return nil
	}
	res, err := executeReadWithCtx(sdk.Context{}, hashline.NewStore(), dir, "many.txt")
	if err != nil {
		t.Fatalf("read failed: %v", err)
	}
	if !strings.Contains(res.Content, "[Showing lines 1-10 of 50. Use :11- to continue]") {
		t.Fatalf("expected read.defaultLimit=10 paging footer, got:\n%s", res.Content)
	}

	// 2. tools.outputMaxColumns (custom value and 0 to disable)
	wideLine := strings.Repeat("a", 120)
	if err := os.WriteFile(filepath.Join(dir, "wide.txt"), []byte(wideLine+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	Setting = func(_ sdk.Context, key string) any {
		if key == "tools.outputMaxColumns" {
			return float64(40)
		}
		return nil
	}
	wRes, err := executeReadWithCtx(sdk.Context{}, hashline.NewStore(), dir, "wide.txt")
	if err != nil {
		t.Fatalf("wide read failed: %v", err)
	}
	if !strings.Contains(wRes.Content, "[Some lines truncated to 40 chars.") {
		t.Fatalf("expected 40-char column cut notice, got:\n%s", wRes.Content)
	}

	Setting = func(_ sdk.Context, key string) any {
		if key == "tools.outputMaxColumns" {
			return float64(0)
		}
		return nil
	}
	wUncut, err := executeReadWithCtx(sdk.Context{}, hashline.NewStore(), dir, "wide.txt")
	if err != nil {
		t.Fatalf("wide uncut read failed: %v", err)
	}
	if strings.Contains(wUncut.Content, "Some lines truncated") || !strings.Contains(wUncut.Content, wideLine) {
		t.Fatalf("expected tools.outputMaxColumns=0 to disable column truncation, got:\n%s", wUncut.Content)
	}

	// 3. tools.artifactSpillThreshold (in KB) caps the read byte budget.
	var bigLines []string
	for i := 1; i <= 40; i++ {
		bigLines = append(bigLines, fmt.Sprintf("L%02d %s", i, strings.Repeat("z", 120)))
	}
	if err := os.WriteFile(filepath.Join(dir, "budget.txt"), []byte(strings.Join(bigLines, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	Setting = func(_ sdk.Context, key string) any {
		if key == "tools.artifactSpillThreshold" {
			return float64(1) // 1 KiB
		}
		return nil
	}
	bRes, err := executeReadWithCtx(sdk.Context{}, hashline.NewStore(), dir, "budget.txt")
	if err != nil {
		t.Fatalf("budget read failed: %v", err)
	}
	if !strings.Contains(bRes.Content, "limit). Use :") {
		t.Fatalf("expected byte-budget truncation under 1KB tools.artifactSpillThreshold, got:\n%s", bRes.Content)
	}

	// 4. Default (Setting == nil): preserves 300-line default limit and 50KB budget.
	Setting = nil
	defRes, err := executeReadWithCtx(sdk.Context{}, hashline.NewStore(), dir, "many.txt")
	if err != nil {
		t.Fatalf("default read failed: %v", err)
	}
	if strings.Contains(defRes.Content, "Showing lines") || !strings.Contains(defRes.Content, "50:row 50") {
		t.Fatalf("expected 50-line file read whole under default limit 300, got:\n%s", defRes.Content)
	}
}
