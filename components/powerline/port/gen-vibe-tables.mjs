// Generates extensions/powerline-footer/working_vibes_tables.go from the ORIGINAL's normalizeEllipsis regex (working-vibes.ts):
// /[\p{Script_Extensions=Han}\p{Script_Extensions=Hiragana}\p{Script_Extensions=Katakana}\p{Script_Extensions=Hangul}\p{Script_Extensions=Bopomofo}]/u
// Go's unicode package has Script but not Script_Extensions, so the class is enumerated by the same regex under the Node that runs the original.
// Usage (from components/powerline): node port/gen-vibe-tables.mjs | gofmt > extensions/powerline-footer/working_vibes_tables.go
const re = /[\p{Script_Extensions=Han}\p{Script_Extensions=Hiragana}\p{Script_Extensions=Katakana}\p{Script_Extensions=Hangul}\p{Script_Extensions=Bopomofo}]/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const hit = !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
  if (hit && start < 0) start = cp;
  if (!hit && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
}
if (start >= 0) ranges.push([start, 0x10ffff]);
const hex = (n) => "0x" + n.toString(16).padStart(n > 0xffff ? 5 : 4, "0");
const r16 = ranges.filter(([, hi]) => hi <= 0xffff);
const r32 = ranges.filter(([lo]) => lo > 0xffff);
let s = `// Code generated by port/gen-vibe-tables.mjs under Node ${process.version} (Unicode ${process.versions.unicode}); DO NOT EDIT.

package powerline_footer

import "unicode"

// cjkScriptExtensions is the character class \\p{Script_Extensions=Han|Hiragana|Katakana|Hangul|Bopomofo} of normalizeEllipsis.
var cjkScriptExtensions = &unicode.RangeTable{
	R16: []unicode.Range16{
`;
for (const [lo, hi] of r16) s += `\t\t{Lo: ${hex(lo)}, Hi: ${hex(hi)}, Stride: 1},\n`;
s += `\t},\n\tR32: []unicode.Range32{\n`;
for (const [lo, hi] of r32) s += `\t\t{Lo: ${hex(lo)}, Hi: ${hex(hi)}, Stride: 1},\n`;
s += `\t},\n}\n`;
process.stdout.write(s);
