// Writes extensions/stretchtext/guide.go from the original's src/prompt.ts, so the guide is byte-identical.
// Usage: node --experimental-transform-types port/gen-guide.mjs port/oracle > extensions/stretchtext/guide.go
import path from "node:path";
import { pathToFileURL } from "node:url";
const { GUIDE } = await import(pathToFileURL(path.join(process.argv[2], "src/prompt.ts")).href);
process.stdout.write(`// Code generated by port/gen-guide.mjs from src/prompt.ts of pi-stretchtext; DO NOT EDIT.
// What stretchtext tells the model, as cc-stretch tells Claude. Guide is cc-stretch's hooks/guide.ts
// unchanged. Copyright (c) 2026 pro-vi, MIT License: https://github.com/pro-vi/cc-stretch

package stretchtext

// Guide is the system-prompt section that teaches the model the \`{{short|long}}\` form.
const Guide = ${JSON.stringify(GUIDE)}
`);
