// TestNoteParityPathHelpersDifferential compares noteRelative, matchNoteDirectory, inside and
// forkScope with the oracle's values (gen2.mjs: testdata/notes_paths_cases.json.gz).
func TestNoteParityPathHelpersDifferential(t *testing.T) {
	raw := testdataGz(t, "notes_paths_cases.json.gz")
	var cases struct {
		Rel []struct {
			P   string  `json:"p"`
			OK  *string `json:"ok"`
			Err string  `json:"err"`
		} `json:"rel"`
		Match []struct {
			T string   `json:"t"`
			D []string `json:"d"`
			R *struct {
				Directory string `json:"directory"`
				Path      string `json:"path"`
			} `json:"r"`
		} `json:"match"`
		Ins []struct {
			D string `json:"d"`
			T string `json:"t"`
			R bool   `json:"r"`
		} `json:"ins"`
		Fork []struct {
			ID        string `json:"id"`
			Timestamp string `json:"timestamp"`
			R         string `json:"r"`
			Err       string `json:"err"`
		} `json:"fork"`
	}
	if err := sdkjson.Unmarshal(raw, &cases); err != nil {
		t.Fatal(err)
	}
	bad := 0
	for _, c := range cases.Rel {
		got, err := noteRelative(c.P)
		switch {
		case c.OK != nil && (err != nil || got != *c.OK):
			bad++
			t.Errorf("noteRelative(%q) = %q, %v; ts %q", c.P, got, err, *c.OK)
		case c.OK == nil && (err == nil || err.Error() != c.Err):
			bad++
			t.Errorf("noteRelative(%q) = %q, %v; ts error %q", c.P, got, err, c.Err)
		}
	}
	for _, c := range cases.Match {
		dir, rel, ok := matchNoteDirectory(c.T, c.D)
		if ok != (c.R != nil) || (ok && (dir != c.R.Directory || rel != c.R.Path)) {
			bad++
			t.Errorf("matchNoteDirectory(%q, %q) = %q %q %v; ts %+v", c.T, c.D, dir, rel, ok, c.R)
		}
	}
	for _, c := range cases.Ins {
		if got := inside(c.D, c.T); got != c.R {
			bad++
			t.Errorf("inside(%q, %q) = %v; ts %v", c.D, c.T, got, c.R)
		}
	}
	for _, c := range cases.Fork {
		got, err := forkScope(noteOwner{id: c.ID, timestamp: c.Timestamp})
		if (c.Err == "" && (err != nil || got != c.R)) || (c.Err != "" && (err == nil || err.Error() != c.Err)) {
			bad++
			t.Errorf("forkScope(%q, %q) = %q, %v; ts %q %q", c.ID, c.Timestamp, got, err, c.R, c.Err)
		}
	}
	t.Logf("%d noteRelative, %d match, %d inside, %d forkScope cases: %d mismatches", len(cases.Rel), len(cases.Match), len(cases.Ins), len(cases.Fork), bad)
}

// Parity with Node: note-scopes.ts:217-231 (seedsOf keys the Map by the touch file's path, `seeds.set(file.path,
// file.seed)`; Go keys it by the seed's own path). Node: seedsOf(...) of this journal is ["z.md"].
func TestNoteParitySeedsOfKeysByFilePath(t *testing.T) {
	root := "/p/.pi/notes"
	addr := func(p string) rec { return rec{"root": root, "scope": "", "path": p} }
	seed := func(p string) rec {
		return rec{"path": p, "source": addr(p), "lineage": addr(p), "anchors": []any{"e1"}, "digest": "abc",
			"identity": rec{"size": 3.0, "mtimeMs": 1.0, "ctimeMs": 1.0, "ino": 1.0, "dev": 1.0}}
	}
	binding := parseBinding(rec{"version": 1.0, "kind": "fork", "owner": nsOwner(), "root": root, "scope": nsForkScope,
		"source": rec{"root": root, "scope": ""}, "seeds": []any{seed("a.md")}, "absent": []any{}})
	if binding == nil {
		t.Fatal("binding rejected")
	}
	touch := rec{"version": 1.0, "owner": nsOwner(), "scope": rec{"root": root, "scope": nsForkScope}, "rootToolCallId": "r", "toolCallId": "c",
		"files": []any{rec{"root": root, "scope": nsForkScope, "path": "a.md", "kind": "adopt", "seed": seed("z.md")}}}
	seeds := seedsOf(binding, []rec{{"type": "custom", "customType": notesTouchType, "data": touch}})
	var got []string
	for _, s := range seeds {
		got = append(got, s.path)
	}
	if len(got) != 1 || got[0] != "z.md" {
		t.Fatalf("seedsOf paths = %q, want [z.md]", got)
	}
}

// TestNoteParityIdentityNumbers: JSON.stringify of NoteIdentity numbers (manifest seeds, touch
// seeds). Expected values are JavaScript's Number::toString.
func TestNoteParityIdentityNumbers(t *testing.T) {
	for f, want := range map[float64]string{
		18446744073709551615: "18446744073709552000", 1e21: "1e+21", 1762430000123.4568: "1762430000123.4568",
		0.1: "0.1", 1.5e-7: "1.5e-7", 5e-324: "5e-324", 9007199254740993: "9007199254740992", 123456789012345680000: "123456789012345680000",
	} {
		if got := string(appendNum(nil, f)); got != want {
			t.Errorf("appendNum(%v) = %s, want %s", f, got, want)
		}
	}
	if got := string(appendNum(nil, math.Copysign(0, -1))); got != "0" {
		t.Errorf("appendNum(-0) = %s, want 0", got)
	}
}

// hostDecidedTimestamp reports a binding whose owner timestamp sdk.ParseDate leaves to the host.
func hostDecidedTimestamp(v any) bool {
	m, _ := v.(map[string]any)
	owner, _ := m["owner"].(map[string]any)
	ts, ok := owner["timestamp"].(string)
	if !ok {
		return false
	}
	_, _, err := sdk.ParseDate(ts)
	return err != nil
}
