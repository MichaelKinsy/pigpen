// TestNoteParityTypeBoxDifferential runs the cases generated by Node (TypeBox Check of the verbatim
// schemas of note-scopes.ts:9-62, parseBinding and touchRecords of the oracle) through the Go validators.
// The cases are testdata/notes_tb_cases.json.gz (gen.mjs).
func TestNoteParityTypeBoxDifferential(t *testing.T) {
	raw := testdataGz(t, "notes_tb_cases.json.gz")
	var cases []struct {
		Name   string `json:"name"`
		Schema string `json:"schema"`
		Value  any    `json:"value"`
		Check  bool   `json:"check"`
		Parse  *bool  `json:"parse"`
		JSON   string `json:"json"`
	}
	if err := sdkjson.Unmarshal(raw, &cases); err != nil {
		t.Fatal(err)
	}
	checks := map[string]func(any) bool{
		"ownerSchema":    func(v any) bool { _, ok := checkOwner(v); return ok },
		"scopeSchema":    func(v any) bool { _, ok := checkScope(v); return ok },
		"addressSchema":  func(v any) bool { _, ok := checkAddress(v); return ok },
		"identitySchema": func(v any) bool { _, ok := checkIdentity(v); return ok },
		"seedSchema":     func(v any) bool { _, ok := checkSeed(v); return ok },
		"bindingSchema":  func(v any) bool { _, ok := checkBinding(v); return ok },
		"touchSchema":    func(v any) bool { _, ok := checkTouch(v); return ok },
	}
	var checkBad, parseBad, jsonBad, hostDecided int
	for _, c := range cases {
		if got := checks[c.Schema](c.Value); got != c.Check {
			checkBad++
			t.Errorf("Check %s: go %v, typebox %v", c.Name, got, c.Check)
		}
		if c.Parse == nil {
			continue
		}
		if c.Schema == "bindingSchema" && hostDecidedTimestamp(c.Value) {
			// Date.parse of a non-canonical timestamp is answered by the host (sdk.ParseDate); no host here.
			hostDecided++
			continue
		}
		var got bool
		var text string
		if c.Schema == "bindingSchema" {
			b := parseBinding(c.Value)
			got = b != nil
			if got {
				text = string(b.appendJSON(nil))
			}
		} else {
			got = len(touchRecords([]rec{{"type": "custom", "customType": notesTouchType, "data": c.Value}})) == 1
		}
		if got != *c.Parse {
			parseBad++
			t.Errorf("parse %s: go %v, ts %v", c.Name, got, *c.Parse)
		}
		if got && *c.Parse && c.JSON != "" && text != c.JSON {
			jsonBad++
			t.Logf("JSON %s:\n go %s\n ts %s", c.Name, text, c.JSON)
		}
	}
	t.Logf("%d cases: %d Check mismatches, %d parse mismatches, %d host-decided timestamps skipped, %d re-serialization differences (extra members, logged)", len(cases), checkBad, parseBad, hostDecided, jsonBad)
}

// Parity with Node: note-scopes.ts:110-121 (canonicalPath rethrows realpathSync's error: the looping
// component is the stat path, not the whole input).
func TestNoteParityCanonicalPathLoopComponent(t *testing.T) {
	root := nsRealTemp(t)
	loop := filepath.Join(root, "loop")
	if err := os.Symlink("loop", loop); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	_, err := canonicalPath(filepath.Join(loop, "file.md"))
	// Node 24: realpathSync("<root>/loop/file.md") throws for the component it stats.
	want := "ELOOP: too many symbolic links encountered, stat '" + loop + "'"
	if err == nil || err.Error() != want {
		t.Fatalf("err = %v\nwant %s", err, want)
	}
}

// Parity with Node: note-scopes.ts:111-113 (realpathSync resolves `..` lexically: lib/fs.js realpathSync
// starts with path.resolve(p); filepath.EvalSymlinks walks `..` after following the symlink).
func TestNoteParityCanonicalPathDotDot(t *testing.T) {
	root := nsRealTemp(t)
	for _, dir := range []string{"root/x", "elsewhere/deep", "elsewhere/x"} {
		if err := os.MkdirAll(filepath.Join(root, dir), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Symlink(filepath.Join(root, "elsewhere", "deep"), filepath.Join(root, "root", "link")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	for in, want := range map[string]string{
		// Node 24 canonicalPath of the same tree (probe4.mjs).
		"root/link/../x":        "root/x",
		"root/link/../x/new.md": "root/x/new.md",
	} {
		got, err := canonicalPath(root + string(filepath.Separator) + filepath.FromSlash(in))
		if err != nil || got != filepath.Join(root, want) {
			t.Errorf("canonicalPath(%s) = %q, %v; want %q", in, got, err, filepath.Join(root, want))
		}
	}
}

