// Parity with Node: note-snapshots.ts:67-71 (JSON.parse keeps a lone surrogate escape; readManifest decodes
// with encoding/json, which turns it into U+FFFD, so a manifest path no longer equals the WTF-8 path the
// SDK delivers and saveAdoption rewrites the manifest with a different string).
func TestNoteParityManifestLoneSurrogate(t *testing.T) {
	root := nsRealTemp(t)
	owner := noteOwner{id: "s1", timestamp: nsTimestamp}
	scope, err := forkScope(owner)
	if err != nil {
		t.Fatal(err)
	}
	var lone string
	if err := sdkjson.Unmarshal([]byte(`"\ud800.md"`), &lone); err != nil {
		t.Fatal(err)
	}
	binding := &noteBinding{kind: "fork", owner: owner, root: root, scope: scope, absent: []string{lone}}
	if parseBinding(mustDecode(t, binding.appendJSON(nil))) == nil {
		t.Fatal("binding with a lone-surrogate absent path rejected")
	}
	if err := ensureManifest(binding); err != nil {
		t.Fatal(err)
	}
	read, err := readManifest(scopeDirectory(binding))
	if err != nil || read == nil {
		t.Fatalf("readManifest = %v, %v", read, err)
	}
	// Node 24: readManifest(...).absent[0] is the lone surrogate "\ud800.md" (length 4, d800).
	if read.absent[0] != lone {
		t.Fatalf("absent[0] = %q (% x), want %q", read.absent[0], read.absent[0], lone)
	}
}

func mustDecode(t *testing.T, data []byte) any {
	t.Helper()
	var v any
	if err := sdkjson.Unmarshal(data, &v); err != nil {
		t.Fatal(err)
	}
	return v
}

