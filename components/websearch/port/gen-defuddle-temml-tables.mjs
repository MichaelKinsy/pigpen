// Generates extensions/websearch/dfd_temml_tables.go from the data tables of temml 0.13.4 (src/symbols.js,
// unicodeSymbols.js, unicodeAccents.js, asciiFromScript.js, unicodeSupOrSub.js). The sources use extensionless
// imports, so a resolve hook adds ".js". Usage (cwd components/websearch):
//   node port/gen-defuddle-temml-tables.mjs <path to temml/src> > extensions/websearch/dfd_temml_tables.go
import { register } from 'node:module'
import path from 'node:path'
const src = path.resolve(process.argv[2])
register('data:text/javascript,' + encodeURIComponent(`
export async function resolve(specifier, context, next) {
  try { return await next(specifier, context) } catch (e) {
    if (specifier.startsWith('.') && !specifier.endsWith('.js')) return next(specifier + '.js', context)
    throw e
  }
}`), import.meta.url)
const symbolsMod = await import(path.join(src, 'symbols.js'))
const uniSym = (await import(path.join(src, 'unicodeSymbols.js'))).default
const uniAcc = (await import(path.join(src, 'unicodeAccents.js'))).default
const { asciiFromScript } = await import(path.join(src, 'asciiFromScript.js'))
const { uSubsAndSups } = await import(path.join(src, 'unicodeSupOrSub.js'))
await import(path.join(src, 'functions.js'))
const { _macros } = await import(path.join(src, 'defineMacro.js'))
const q = (s) => JSON.stringify(s).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')
const o = []
o.push('// Code generated by port/gen-defuddle-temml-tables.mjs from temml 0.13.4 (MIT); DO NOT EDIT.', '', 'package websearch', '')
o.push('type tmSymbol struct{ group, replace string }', '')
for (const mode of ['math', 'text']) {
  o.push(`var tmSymbols${mode[0].toUpperCase() + mode.slice(1)} = map[string]*tmSymbol{`)
  // entries that share an object (acceptUnicodeChar) are emitted as separate but equal values: nothing mutates them
  for (const [k, v] of Object.entries(symbolsMod.default[mode])) o.push(`\t${q(k)}: {${q(v.group)}, ${v.replace == null ? '""' : q(v.replace)}},`)
  o.push('}', '')
}
// "replace" can be undefined or an empty string: record which symbols have a defined, non-empty replace
o.push('var tmLigatures = map[string]bool{')
for (const k of Object.keys(symbolsMod.ligatures)) o.push(`\t${q(k)}: true,`)
o.push('}', '', 'var tmUnicodeSymbols = map[string]string{')
for (const [k, v] of Object.entries(uniSym)) o.push(`\t${q(k)}: ${q(v)},`)
o.push('}', '', 'type tmAccentCmd struct{ text, math string }', '', 'var tmUnicodeAccents = map[string]tmAccentCmd{')
for (const [k, v] of Object.entries(uniAcc)) o.push(`\t${q(k)}: {${q(v.text || '')}, ${q(v.math || '')}},`)
o.push('}', '', 'var tmAsciiFromScript = map[string]string{')
for (const [k, v] of Object.entries(asciiFromScript)) o.push(`\t${q(k)}: ${q(v)},`)
o.push('}', '', 'var tmSubsAndSups = map[string]string{')
for (const [k, v] of Object.entries(uSubsAndSups)) o.push(`\t${q(k)}: ${q(v)},`)
o.push('}', '')
{
  // the xcolor names of src/functions/color.js, a JSON.parse of a template literal
  const colorSrc = (await import('node:fs')).readFileSync(path.join(src, 'functions/color.js'), 'utf8')
  const m = /JSON\.parse\(`([^`]*)`\)/.exec(colorSrc)
  const xcolors = JSON.parse(m[1])
  o.push('var tmXColors = map[string]string{')
  for (const [k, v] of Object.entries(xcolors)) o.push(`\t${q(k)}: ${q(v)},`)
  o.push('}', '')
}
o.push('// Macros defined as a string (the macros defined by a function are in dfd_temml_macros.go):', '', 'var tmStringMacros = map[string]string{')
const fnMacros = []
for (const [k, v] of Object.entries(_macros)) { if (typeof v === 'string') o.push(`\t${q(k)}: ${q(v)},`); else fnMacros.push(k) }
o.push('}', '', '// Macros defined by a function: ' + fnMacros.join(' '), '')
// The macros the bundled dist/temml.cjs adds to src/: mhchem's dash macros, texvc.sty and the physics package. Their
// source is evaluated with a stub defineMacro.
if (process.argv[3]) {
  const dist = (await import('node:fs')).readFileSync(process.argv[3], 'utf8')
  const found = {}
  const run = (code) => new Function('defineMacro', code)((name, body) => { if (typeof body === 'string') found[name] = body })
  const mh = dist.slice(dist.indexOf('// Add \\ce, \\pu, and \\tripleDash'), dist.indexOf('  //\n  //  This is the main function for handing the \\ce'))
  run(mh.replace(/defineMacro\("\\\\ce"[\s\S]*?\n\}\);\n\ndefineMacro\("\\\\pu"[\s\S]*?\n\}\);/, ''))
  const tx = dist.slice(dist.indexOf('// texvc.sty'), dist.indexOf('// Helper functions'))
  run(tx)
  // mhchem: the state machine tables (as createTransitions builds them) and the regular expression patterns
  const mhCode = dist.slice(dist.indexOf('// Add \\ce, \\pu, and \\tripleDash'), dist.indexOf('// texvc.sty'))
  const mhc = new Function('defineMacro', mhCode + '\nreturn { mhchemParser }')(() => {})
  o.push('type tmMhAct struct{ typ, option string }', '', 'type tmMhTrans struct {', '\tpattern string', '\tactions []tmMhAct', '\tnextState string', '\trevisit, toContinue bool', '}', '')
  o.push('var tmMhTransitions = map[string]map[string][]tmMhTrans{')
  for (const [mname, mach] of Object.entries(mhc.mhchemParser.stateMachines)) {
    o.push(`\t${q(mname)}: {`)
    for (const [state, list] of Object.entries(mach.transitions)) {
      o.push(`\t\t${q(state)}: {`)
      for (const t of list) {
        const acts = t.task.action_.map((a) => `{${q(a.type_)}, ${q(a.option === undefined ? '' : String(a.option))}}`).join(', ')
        o.push(`\t\t\t{${q(t.pattern)}, []tmMhAct{${acts}}, ${q(t.task.nextState || '')}, ${!!t.task.revisit}, ${!!t.task.toContinue}},`)
      }
      o.push('\t\t},')
    }
    o.push('\t},')
  }
  o.push('}', '', 'var tmMhRegexPatterns = map[string]string{')
  for (const [name, pat] of Object.entries(mhc.mhchemParser.patterns.patterns)) if (typeof pat !== 'function') o.push(`\t${q(name)}: ${q(pat.source)},`)
  o.push('}', '')
  o.push('// Macros of the bundled dist/temml.cjs (mhchem dashes, texvc.sty, physics):', '', 'var tmDistMacros = map[string]string{')
  for (const [k, v] of Object.entries(found)) o.push(`\t${q(k)}: ${q(v)},`)
  o.push('}', '')
}
process.stdout.write(o.join('\n'))
