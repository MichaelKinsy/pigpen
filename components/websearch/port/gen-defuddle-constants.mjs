// Generates extensions/websearch/defuddle_constants.go from the lists and sets of defuddle 0.19.3's dist/constants.js
// (the vendored original in port/oracle/node_modules), so the Go port's selector lists, allowed attributes and
// colour tables are the library's own and not a retyped copy.
//
//   node port/gen-defuddle-constants.mjs > extensions/websearch/defuddle_constants.go
import { createRequire } from "node:module";

const require = createRequire(new URL("./oracle/package.json", import.meta.url));
// DEFUDDLE_DIST points at another copy of the same dist directory (for running without the oracle's node_modules).
const dist = process.env.DEFUDDLE_DIST ?? new URL("./oracle/node_modules/defuddle/dist", import.meta.url).pathname;
const c = require(dist + "/constants.js");

const q = (s) => JSON.stringify(s).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
const out = [];
out.push("// Code generated by port/gen-defuddle-constants.mjs from defuddle 0.19.3 dist/constants.js; DO NOT EDIT.");
out.push("");
out.push("package websearch");
out.push("");
const list = (name, arr) => {
	out.push(`var ${name} = []string{`);
	for (const s of arr) out.push(`\t${q(s)},`);
	out.push("}");
	out.push("");
};
const str = (name, s) => { out.push(`const ${name} = ${q(s)}`); out.push(""); };
const set = (name, s) => {
	out.push(`var ${name} = map[string]bool{`);
	for (const v of s) out.push(`\t${q(v)}: true,`);
	out.push("}");
	out.push("");
};

list("dfdEntryPointElements", c.ENTRY_POINT_ELEMENTS);
out.push(`const dfdMobileWidth = ${c.MOBILE_WIDTH}`);
out.push("");
list("dfdBlockElements", c.BLOCK_ELEMENTS);
str("dfdBlockElementsSelector", c.BLOCK_ELEMENTS_SELECTOR);
set("dfdBlockElementsSet", c.BLOCK_ELEMENTS_SET);
set("dfdBlockLevelElements", c.BLOCK_LEVEL_ELEMENTS);
set("dfdPreserveElements", c.PRESERVE_ELEMENTS);
set("dfdInlineElements", c.INLINE_ELEMENTS);
str("dfdContentElementSelector", c.CONTENT_ELEMENT_SELECTOR);
str("dfdHiddenExactSelector", c.HIDDEN_EXACT_SELECTOR);
str("dfdHiddenExactSkipSelector", c.HIDDEN_EXACT_SKIP_SELECTOR);
list("dfdExactSelectors", c.EXACT_SELECTORS);
str("dfdExactSelectorsJoined", c.EXACT_SELECTORS_JOINED);
list("dfdTestAttributes", c.TEST_ATTRIBUTES);
str("dfdTestAttributesSelector", c.TEST_ATTRIBUTES_SELECTOR);
list("dfdPartialSelectors", c.PARTIAL_SELECTORS);
str("dfdFootnoteInlineReferences", c.FOOTNOTE_INLINE_REFERENCES);
str("dfdFootnoteListSelectors", c.FOOTNOTE_LIST_SELECTORS);
set("dfdAllowedEmptyElements", c.ALLOWED_EMPTY_ELEMENTS);
set("dfdAllowedAttributes", c.ALLOWED_ATTRIBUTES);
set("dfdAllowedAttributesDebug", c.ALLOWED_ATTRIBUTES_DEBUG);
const mapOf = (name, o) => {
	out.push(`var ${name} = map[string]string{`);
	for (const k of Object.keys(o)) out.push(`\t${q(k)}: ${q(String(o[k]))},`);
	out.push("}");
	out.push("");
};
out.push("var dfdTailwindColors = map[string]map[string]string{");
for (const k of Object.keys(c.TAILWIND_COLORS)) {
	out.push(`\t${q(k)}: {`);
	for (const s of Object.keys(c.TAILWIND_COLORS[k])) out.push(`\t\t${q(s)}: ${q(c.TAILWIND_COLORS[k][s])},`);
	out.push("\t},");
}
out.push("}");
out.push("");
mapOf("dfdTailwindSpecial", c.TAILWIND_SPECIAL);
process.stdout.write(out.join("\n"));
