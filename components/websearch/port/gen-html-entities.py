#!/usr/bin/env python3
"""Generates extensions/websearch/ldom_entities.go: the HTML named character references (the table of the HTML
standard, as in Python's html.entities.html5) that the port of htmlparser2's entity decoding needs.

    python3 port/gen-html-entities.py > extensions/websearch/ldom_entities.go
"""
from html.entities import html5

names = sorted(k for k in html5 if k.endswith(";"))
legacy = sorted(k for k in html5 if not k.endswith(";"))
for k in legacy:
    assert k + ";" in html5 and html5[k] == html5[k + ";"]


def q(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        else:
            out.append("\\U%08x" % o)
    return '"' + "".join(out) + '"'


print("// Code generated by port/gen-html-entities.py; DO NOT EDIT.")
print()
print("package websearch")
print()
print("// ldEntities maps each named character reference with its semicolon to its characters.")
print("var ldEntities = map[string]string{")
for k in names:
    print("\t%s: %s," % (q(k[:-1]), q(html5[k])))
print("}")
print()
print("// ldLegacyEntities are the names that also decode without a semicolon.")
print("var ldLegacyEntities = map[string]bool{")
for k in legacy:
    print("\t%s: true," % q(k))
print("}")
