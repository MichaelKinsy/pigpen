#!/usr/bin/env python3
"""Packs a run.sh work directory into the committed testdata of bashparse's differential.

  python3 pack-testdata.py <work dir> <bashparse/testdata dir>

Writes (all gzip):
  corpus-a.jsonl.gz   {"s","g","p"} per original-test string: the original's full node dumps
  corpus-b.json.gz    the other test strings (inputs; hashes below)
  shapes.json.gz      the hand-built shape corpus (inputs)
  hash-<kind>.bin.gz  one little-endian uint32 per input of <kind> in {b, shapes, prefix, del, fuzz}:
                      FNV-1a/32 of grammarDump + "\\x01" + correctedDump, as recorded from the original
The prefix/deletion variants and the fuzz inputs are regenerated by the Go test from corpus a and the
shapes (variants: gen-variants.mjs's rule; fuzz: fuzzgen_test.go), so only their hashes are stored.
"""
import gzip
import json
import os
import struct
import sys

work, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)

def gz(path, data):
    with gzip.GzipFile(path, "wb", compresslevel=9, mtime=0) as f:
        f.write(data)

def fnv(s):
    h = 0x811C9DC5
    for b in s.encode("ascii"):
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h

def read(name):
    with open(os.path.join(work, name), "rb") as f:
        return f.read()

gz(os.path.join(out, "corpus-a.jsonl.gz"), read("full-a.jsonl"))
gz(os.path.join(out, "corpus-b.json.gz"), read("in-b.json"))
gz(os.path.join(out, "shapes.json.gz"), read("in-shapes.json"))

def hashes_from_full(name):
    out_h = []
    with open(os.path.join(work, name), encoding="utf-8") as f:
        for line in f:
            rec = json.loads(line)
            out_h.append(fnv(rec["g"] + "\x01" + rec["p"]))
    return out_h

def hashes_from_txt(name):
    with open(os.path.join(work, name)) as f:
        return [int(x, 16) for x in f.read().split()]

kinds = {
    "b": lambda: hashes_from_full("full-b.jsonl"),
    "shapes": lambda: hashes_from_full("full-shapes.jsonl"),
    "prefix": lambda: hashes_from_txt("hash-prefix.txt"),
    "del": lambda: hashes_from_txt("hash-del.txt"),
    "fuzz": lambda: hashes_from_txt("hash-fuzz.txt"),
}
for kind, load in kinds.items():
    if kind == "fuzz" and not os.path.exists(os.path.join(work, "hash-fuzz.txt")):
        continue
    hs = load()
    gz(os.path.join(out, "hash-%s.bin.gz" % kind), b"".join(struct.pack("<I", h) for h in hs))
    print(kind, len(hs))
