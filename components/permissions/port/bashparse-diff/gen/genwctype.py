#!/usr/bin/env python3
"""Generates bashparse/internal/ts/wctype_gen.go from wctype.json, the iswalpha / iswspace ranges
recorded from the original (wctype.test.ts, run-wctype.sh).

  python3 genwctype.py wctype.json <out wctype_gen.go>

ASCII is fixed to what C's classes say (the probe sees extra ASCII "letters" because the scanner has
other branches for digits, '+', '=' and '_'); everything from U+0080 is the recording.
"""
import json
import sys

d = json.load(open(sys.argv[1]))
alpha = [[65, 90], [97, 122]] + [r for r in d["alpha"] if r[0] >= 128]
space = [r for r in d["space"] if r[0] > 0]
for name, rs in (("alpha", alpha), ("space", space)):
    for i in range(1, len(rs)):
        assert rs[i - 1][1] < rs[i][0], name

def table(name, ranges):
    rows = ",\n".join("\t{0x%x, 0x%x}" % (a, b) for a, b in ranges)
    return "var %s = []charRange{\n%s,\n}\n" % (name, rows)

out = [
    "// Code generated by port/bashparse-diff/gen/genwctype.py from wctype.json; DO NOT EDIT.",
    "",
    "package ts",
    "",
    "// iswalpha and iswspace are the wide-character classes the language's wasm external scanner calls",
    "// (wasi-libc, a musl). The ranges are recorded from the original by probing parses whose tree depends",
    "// on each class (port/bashparse-diff/wctype.test.ts), not copied from a libc.",
    "func iswalpha(c int32) bool { return setContains(alphaRanges, c) }",
    "",
    "func iswspace(c int32) bool { return setContains(spaceRanges, c) }",
    "",
    table("alphaRanges", alpha),
    table("spaceRanges", space),
]
open(sys.argv[2], "w").write("\n".join(out))
