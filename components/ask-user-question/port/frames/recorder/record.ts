// ---- recording theme -------------------------------------------------------------------------------------------
interface Palette {
	fg: string[];
	bg: string[];
}
const palette = JSON.parse(readFileSync(path.join(framesDir, "theme-tokens.json"), "utf8")) as Palette;
const fgIndex: Record<string, number> = Object.fromEntries(palette.fg.map((n, i) => [n, 16 + i]));
const bgIndex: Record<string, number> = Object.fromEntries(palette.bg.map((n, i) => [n, 16 + i]));
const ESC = "\x1b";

function sgr(open: string, text: string, close: string): string {
	return `${ESC}[${open}m${text}${ESC}[${close}m`;
}

const themeImpl: Record<string, (...args: string[]) => string> = {
	fg(color, text) {
		const n = fgIndex[color];
		if (n === undefined) throw new Error(`recording theme: unknown fg token ${JSON.stringify(color)}`);
		return sgr(`38;5;${n}`, text, "39");
	},
	bg(color, text) {
		const n = bgIndex[color];
		if (n === undefined) throw new Error(`recording theme: unknown bg token ${JSON.stringify(color)}`);
		return sgr(`48;5;${n}`, text, "49");
	},
	bold: (text) => sgr("1", text, "22"),
	italic: (text) => sgr("3", text, "23"),
	underline: (text) => sgr("4", text, "24"),
	strikethrough: (text) => sgr("9", text, "29"),
	inverse: (text) => sgr("7", text, "27"),
};
// A Theme member the oracle calls that the recording theme lacks must fail loudly, not return undefined.
// Cast: the Proxy implements exactly the Theme members the oracle uses; the rest of the class is deliberately absent.
const recordingTheme = new Proxy(themeImpl, {
	get(target, prop) {
		if (typeof prop === "symbol" || prop === "then") return undefined;
		if (prop in target) return target[prop];
		throw new Error(`recording theme: the oracle called Theme.${prop}, which the recording theme does not implement`);
	},
}) as unknown as Theme;

initTheme("dark");
// pi-coding-agent shares its theme through this globalThis slot (theme.js THEME_KEY); its exported `theme` proxy reads it,
// and getMarkdownTheme() and the code highlighter go through that proxy.
Reflect.set(globalThis, Symbol.for("@earendil-works/pi-coding-agent:theme"), recordingTheme);

const NAMED_SGR: Record<string, string> = {
	"0": "<reset>",
	"1": "<b>",
	"22": "</b>",
	"3": "<i>",
	"23": "</i>",
	"4": "<u>",
	"24": "</u>",
	"9": "<s>",
	"29": "</s>",
	"7": "<inv>",
	"27": "</inv>",
	"39": "</fg>",
	"49": "</bg>",
};

// SGR -> tag, the stored form of a frame line. The Go test has the same function (tagify in frames_test.go).
function sgrTags(params: string): string {
	const p = (params === "" ? "0" : params).split(";");
	const out: string[] = [];
	for (let i = 0; i < p.length; ) {
		const c = p[i];
		if ((c === "38" || c === "48") && p[i + 1] === "5" && i + 2 < p.length) {
			const n = Number(p[i + 2]);
			const list = c === "38" ? palette.fg : palette.bg;
			const name = Number.isInteger(n) && n >= 16 && n - 16 < list.length ? list[n - 16] : `?${p[i + 2]}`;
			out.push(`<${c === "38" ? "fg" : "bg"}:${name}>`);
			i += 3;
		} else if ((c === "38" || c === "48") && p[i + 1] === "2" && i + 4 < p.length) {
			out.push(`<sgr:${p.slice(i, i + 5).join(";")}>`);
			i += 5;
		} else {
			out.push(NAMED_SGR[c] ?? `<sgr:${c}>`);
			i++;
		}
	}
	return out.length === 1 ? out[0] : `<+${out.join("")}+>`;
}

function tagify(line: string): string {
	return line.replace(/\x1b\[([0-9;]*)m/g, (_m, params: string) => sgrTags(params));
}

// ---- keybindings -----------------------------------------------------------------------------------------------
// Pi's KeybindingsManager (pi-coding-agent core/keybindings.js) is not exported from its package entry; it is
// pi-tui's KeybindingsManager over pi-tui's tui.* table plus the app.* ids. The questionnaire matches tui.* and
// app.editor.external only (state/key-router.ts), so those are the ids defined here, with Pi's default for the last.
const definitions = {
	...TUI_KEYBINDINGS,
	"app.editor.external": { defaultKeys: "ctrl+g", description: "Open external editor" },
};

// ---- scenarios -------------------------------------------------------------------------------------------------
interface Step {
	input: string;
	label?: string;
	render?: boolean;
	settle?: "notify";
	resize?: { width: number; rows: number };
}
interface Scenario {
	name: string;
	description?: string;
	params: unknown;
	width: number;
	rows: number;
	collapseKey?: string;
	locale?: string;
	keybindings?: Record<string, string | string[]>;
	rawInput?: boolean;
	hyperlinks?: boolean;
	steps: Step[];
}
interface Component {
	render(width: number): string[];
	handleInput(data: string): void;
}
interface Handle {
	hidden: boolean;
	setHidden(hidden: boolean): void;
	isHidden(): boolean;
	isFocused(): boolean;
}
interface InputResult {
	consume?: boolean;
	data?: string;
}
type InputListener = (data: string) => InputResult | undefined;
type ComponentFactory = (tui: unknown, theme: Theme, keybindings: unknown, done: (result: unknown) => void) => Component;
interface CustomOptions {
	onHandle: (handle: Handle) => void;
}
interface ToolDefinition {
	execute(id: string, params: unknown, signal: undefined, onUpdate: undefined, ctx: ExtensionContext): Promise<unknown>;
}

// JSON round trip: what the host would serialise; `undefined` becomes null so a missing result is visible.
function clone<T>(v: T): T {
	return v === undefined ? (null as T) : (JSON.parse(JSON.stringify(v)) as T);
}

const piTuiPackage = JSON.parse(
	readFileSync(path.join(path.dirname(fileURLToPath(import.meta.resolve("@earendil-works/pi-tui"))), "..", "package.json"), "utf8"),
) as { version: string };

async function record(sc: Scenario) {
	const xdg = mkdtempSync(path.join(scratch, "xdg-"));
	process.env.XDG_CONFIG_HOME = xdg;
	if (sc.collapseKey !== undefined) {
		mkdirSync(path.join(xdg, "rpiv-ask-user-question"), { recursive: true });
		writeFileSync(path.join(xdg, "rpiv-ask-user-question", "config.json"), JSON.stringify({ collapseKey: sc.collapseKey }));
	}
	applyLocale(sc.locale);
	// OSC 8 hyperlink support is detected from the environment; pin it (default off, as in a plain container).
	setCapabilityOverrides({ hyperlinks: sc.hyperlinks === true });

	const kb = new KeybindingsManager(definitions, sc.keybindings ?? {});
	setKeybindings(kb);

	const events: { channel: string; payload: unknown }[] = [];
	let tool: ToolDefinition | undefined;
	// Cast: the registration only reads pi.events.emit and calls pi.registerTool; the rest of ExtensionAPI is not touched.
	registerAskUserQuestionTool({
		events: { emit: (channel: string, payload: unknown) => events.push({ channel, payload: clone(payload) }) },
		registerTool: (def: ToolDefinition) => {
			tool = def;
		},
		on: () => undefined,
	} as unknown as ExtensionAPI);
	if (!tool) throw new Error("the oracle registered no tool");

	let width = sc.width;
	let rows = sc.rows;
	let renders = 0;
	const fakeTui = {
		requestRender: () => {
			renders++;
		},
		terminal: { columns: width, rows },
	};
	let component: Component | undefined;
	let handle: Handle | undefined;
	let result: unknown;
	let doneCount = 0;
	let listener: InputListener | undefined;
	let listenerRegistered = false;
	let listenerRemoved = false;
	const notifications: { message: string; level: string }[] = [];
	let notifyWaiter: (() => void) | undefined;
	const customCalled = Promise.withResolvers<void>();

	const ctx = {
		hasUI: true,
		mode: "tui",
		cwd: scratch,
		isProjectTrusted: () => false,
		ui: {
			custom: (factory: ComponentFactory, options: CustomOptions) => {
				const { promise, resolve } = Promise.withResolvers<unknown>();
				const done = (r: unknown) => {
					doneCount++;
					result = clone(r);
					resolve(r);
				};
				component = factory(fakeTui, recordingTheme, kb, done);
				handle = {
					hidden: false,
					setHidden(h) {
						this.hidden = h;
					},
					isHidden() {
						return this.hidden;
					},
					isFocused() {
						return !this.hidden;
					},
				};
				options.onHandle(handle);
				customCalled.resolve();
				return promise;
			},
			notify: (message: string, level: string) => {
				notifications.push({ message, level });
				notifyWaiter?.();
			},
			...(sc.rawInput === false
				? {}
				: {
						onTerminalInput: (h: InputListener) => {
							listener = h;
							listenerRegistered = true;
							return () => {
								listener = undefined;
								listenerRemoved = true;
							};
						},
					}),
		},
	};

	// Cast: the fake context carries exactly the members execute() reads (hasUI, mode, cwd, isProjectTrusted, ui.*).
	const exec = tool.execute("call-1", clone(sc.params), undefined, undefined, ctx as unknown as ExtensionContext);
	await Promise.race([customCalled.promise, exec.then(() => Promise.reject(new Error(`${sc.name}: execute returned before custom()`)))]);
	if (!component || !handle) throw new Error(`${sc.name}: the factory produced no component`);
	const comp = component;
	const overlay = handle;

	const frames: Record<string, unknown>[] = [];
	const snap = (extra: Record<string, unknown>) => {
		frames.push({ ...extra, lines: comp.render(width).map(tagify), hidden: overlay.hidden, renders });
	};
	// A scenario that does not complete is a scenario bug: the message carries the last frame so it can be fixed.
	const fail = (msg: string): never => {
		const last = frames[frames.length - 1];
		throw new Error(`${sc.name}: ${msg}\n${(last?.lines as string[] | undefined)?.join("\n") ?? ""}`);
	};
	snap({ step: 0, label: "initial" });
	for (const [i, step] of sc.steps.entries()) {
		if (doneCount > 0) fail(`step ${i + 1} follows done()`);
		if (step.resize) {
			width = step.resize.width;
			rows = step.resize.rows;
			fakeTui.terminal.columns = width;
			fakeTui.terminal.rows = rows;
		}
		let consumed = false;
		const waiter = step.settle === "notify" ? new Promise<void>((r) => (notifyWaiter = r)) : undefined;
		// pi-tui handleInput: raw listeners first; a hidden overlay gets no input; key releases are dropped.
		if (listener?.(step.input)?.consume) {
			consumed = true;
		} else if (!overlay.hidden && !isKeyRelease(step.input)) {
			comp.handleInput(step.input);
		}
		if (waiter) {
			await waiter;
			await new Promise((r) => setTimeout(r, 5));
			notifyWaiter = undefined;
		}
		if (step.render === false) continue;
		snap({ step: i + 1, label: step.label ?? null, input: step.input, ...(consumed ? { consumed: true } : {}) });
	}
	if (doneCount !== 1) fail(`expected exactly one done(), got ${doneCount}`);
	const timeout = new Promise<never>((_, rej) => setTimeout(() => rej(new Error(`${sc.name}: execute did not settle`)), 5000));
	const toolResult = await Promise.race([exec, timeout]);

	return {
		scenario: sc.name,
		oracle: { package: "@juicesharp/rpiv-ask-user-question@2.11.0", pi: `${piTuiPackage.version}+${process.env.PI_COMMIT}` },
		frames,
		result,
		toolResult: clone(toolResult),
		events,
		notifications,
		listener: { registered: listenerRegistered, removed: listenerRemoved },
	};
}

const scenarioDir = path.join(framesDir, "scenarios");
const goldenDir = path.join(framesDir, "golden");
mkdirSync(goldenDir, { recursive: true });
// The oracle's locales, registered the way index.ts does (the SDK is installed here, so t() is the live SDK scope).
registerLocalesFromDir(I18N_NAMESPACE, pathToFileURL(path.join(oracleDir, "index.ts")).href, {
	label: "rpiv-ask-user-question",
});

const only = process.argv.slice(2);
const failures: string[] = [];
let total = 0;
let count = 0;
for (const file of readdirSync(scenarioDir)
	.filter((f) => f.endsWith(".json"))
	.sort()) {
	const sc = JSON.parse(readFileSync(path.join(scenarioDir, file), "utf8")) as Scenario;
	if (only.length > 0 && !only.includes(sc.name)) continue;
	if (`${sc.name}.json` !== file) throw new Error(`${file}: scenario name ${sc.name} does not match the file name`);
	try {
		const golden = await record(sc);
		writeFileSync(path.join(goldenDir, `${sc.name}.json`), `${JSON.stringify(golden, null, "\t")}\n`);
		total += golden.frames.length;
		count++;
	} catch (e) {
		failures.push(e instanceof Error ? e.message : String(e));
	}
}
console.log(`recorded ${count} scenarios, ${total} frames`);
for (const f of failures) console.error(`FAILED ${f}`);
process.exit(failures.length > 0 ? 1 : 0);
